#!/usr/bin/env python3
"""Post-hoc (descriptive) breakdowns of the frozen M5 runs: SAT/UNSAT strata.

  scripts/m5_posthoc.py --runs results/m5_heldout/runs.csv --out reports/m5/posthoc.md

Observed answer = verified answer of any run on that instance (SAT/UNSAT),
else 'unsolved'.  Used only for stratified reporting, never as a policy input.
"""

import argparse
import os
import sys

import numpy as np
import pandas as pd

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "analysis"))
import fpstats as fs  # noqa: E402

ORDER = ["sw10k_Crev", "Iminus", "D", "Fminus", "Fplus", "sw1k_Crev", "sw100k_Crev", "sw10k_C",
         "pol_m3_D_K1000_time"]
NAMES = {"sw10k_Crev": "F−→D @1e4 (candidate)", "Iminus": "I− (SBS)", "D": "D", "Fminus": "F−",
         "Fplus": "F+", "sw1k_Crev": "F−→D @1e3", "sw100k_Crev": "F−→D @1e5", "sw10k_C": "D→F− @1e4",
         "pol_m3_D_K1000_time": "M3 selector"}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    df = fs.load_runs(a.runs)
    T = float(df.timeout.iloc[0])
    ans = df[df.status == "solved"].groupby("instance").result.agg(lambda s: s.iloc[0])
    meta = fs.instance_meta(df)
    out = ["# M5 post-hoc breakdown by observed answer (descriptive; generated by scripts/m5_posthoc.py)\n",
           "Solved = mean over seeds 0/1/2 of verified solved instances; PAR2 = mean over instances of the seed-mean.\n"]
    for name, sel in (("test (family-disjoint)", meta.split == "test"), ("t2026", meta.split == "t2026")):
        insts = meta.index[sel]
        d = df[df.instance.isin(insts)]
        stratum = pd.Series("unsolved", index=insts)
        stratum.loc[stratum.index.intersection(ans.index)] = ans
        rows = []
        for s in ("SAT", "UNSAT", "unsolved"):
            ii = stratum.index[stratum == s]
            r = {"stratum": s, "instances": len(ii)}
            for c in ORDER:
                x = d[(d.config == c) & d.instance.isin(ii)]
                if x.empty:
                    continue
                r[f"{NAMES[c]} solved"] = (x.status == "solved").sum() / 3
                r[f"{NAMES[c]} PAR2"] = x.groupby("instance").par2.mean().mean()
            rows.append(r)
        t = pd.DataFrame(rows)
        out.append(f"\n## {name}\n")
        cols = ["stratum", "instances"] + [c for c in t.columns if c.endswith("solved") and c != "instances"]
        out.append(fs.md_table(t[cols], "{:.1f}"))
        out.append("")
        cols = ["stratum", "instances"] + [c for c in t.columns if c.endswith("PAR2")]
        out.append(fs.md_table(t[cols], "{:.1f}"))
    with open(a.out, "w") as f:
        f.write("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
