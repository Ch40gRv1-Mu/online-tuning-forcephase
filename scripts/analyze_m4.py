#!/usr/bin/env python3
"""M4-lite: observation-free fixed schedules on dev (seed 0), and the
pre-registered choice of the M5 primary candidate.

  scripts/analyze_m4.py --census results/m2_census/runs.csv --replay results/m3_replay/runs.csv \
      --m4 results/m4/runs.csv --m3 reports/m3/selectors.csv --out reports/m4

Schedules that start with F- and switch at K were only run on instances whose
census F- run reached checkpoint K; on the other instances the schedule is
identical to F- (deterministic search; it finishes before the switch), so the
census F- record is used there.  Mode-only schedules were run on all dev
instances.  Candidate rule (EXPERIMENT_LOG 2026-10-18 22:15): lowest dev mean
PAR2 among deployable dev-evaluated policies (M3 out-of-fold selectors, M4-lite
fixed schedules including F- -> D @1e4).
"""

import argparse
import json
import os
import sys

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "analysis"))
import fpstats as fs  # noqa: E402

T = 300.0
SCHEDULES = {  # config -> (label, starts with F- and switches at K?)
    "sw1k_Crev": ("F−→D @1e3", True), "sw10k_Crev": ("F−→D @1e4", True), "sw100k_Crev": ("F−→D @1e5", True),
    "sw1k_CrevIn": ("F−→I− @1e3", True), "sw10k_CrevIn": ("F−→I− @1e4", True),
    "sw100k_CrevIn": ("F−→I− @1e5", True), "sw10k_Crev_rlim": ("F−→D @1e4, rephase postponed", True),
    "mode_negfocused": ("NEG in focused / NAT in stable", False),
    "mode_negstable": ("NEG in stable / NAT in focused", False),
}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--census", required=True)
    ap.add_argument("--replay", required=True)
    ap.add_argument("--m4", required=True)
    ap.add_argument("--m3", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    os.makedirs(os.path.join(a.out, "figures"), exist_ok=True)
    census = fs.load_runs(a.census)
    census = census[census.split.isin(["train", "val"])]
    runs = pd.concat([fs.load_runs(a.replay), fs.load_runs(a.m4)], ignore_index=True)
    runs = runs[runs.split.isin(["train", "val"])]
    wide = fs.wide_cost(census, ["D", "Iminus", "Fminus", "Fplus"])
    solved_c = fs.wide_solved(census, ["D", "Iminus", "Fminus", "Fplus"])
    meta = fs.instance_meta(census)
    insts = wide.index.values
    groups = meta.loc[insts, "family_group"].values
    ans, _ = fs.observed_answer(pd.concat([census, runs], ignore_index=True))
    ansf = pd.Series("unknown", index=insts)
    ansf.loc[ansf.index.intersection(ans.index)] = ans
    costs = {"D (stock)": wide["D"].values, "I− (validation-SBS)": wide["Iminus"].values,
             "F− (forced negative)": wide["Fminus"].values, "F+ (forced positive)": wide["Fplus"].values}
    solved = {k: (v < 2 * T) for k, v in costs.items()}
    for cfg, (label, from_f) in SCHEDULES.items():
        r = runs[runs.config == cfg].set_index("instance")
        if r.empty:
            continue
        c = r.par2.reindex(insts)
        if from_f:
            c = c.fillna(pd.Series(wide["Fminus"].values, index=insts))
        if c.isna().any():
            print(f"warning: {cfg} missing {int(c.isna().sum())} instances")
            continue
        costs[label] = c.values
        solved[label] = c.values < 2 * T
    rows = []
    for name, c in costs.items():
        p, lo, hi = fs.paired_relative_ci(costs["D (stock)"], c, groups)
        q, qlo, qhi = fs.paired_relative_ci(costs["I− (validation-SBS)"], c, groups)
        s = c < 2 * T
        rows.append({"policy": name, "PAR2": c.mean(), "solved": int(s.sum()),
                     "SAT": int((s & (ansf.values == "SAT")).sum()), "UNSAT": int((s & (ansf.values == "UNSAT")).sum()),
                     "vs D %": 100 * p, "D lo": 100 * lo, "D hi": 100 * hi,
                     "vs I− %": 100 * q, "I− lo": 100 * qlo, "I− hi": 100 * qhi})
    t = pd.DataFrame(rows)
    out = ["# M4-lite fixed schedules on dev (generated by scripts/analyze_m4.py)\n",
           "Dev = train+val, 817 instances, seed 0, T = 300 s. Relative PAR2 reduction (positive = better) with 95% "
           "family-group cluster bootstrap CIs. SAT/UNSAT = post-hoc observed answers.\n"]
    out.append(fs.md_table(t, "{:.1f}"))

    # per-split view (train / val) for the schedules
    out.append("\n\n## Train and validation separately (mean PAR2)\n")
    rows = []
    for name, c in costs.items():
        r = {"policy": name}
        for sp in ("train", "val"):
            m = (meta.loc[insts, "split"] == sp).values
            r[f"{sp} PAR2"] = c[m].mean()
            r[f"{sp} solved"] = int((c[m] < 2 * T).sum())
        rows.append(r)
    out.append(fs.md_table(pd.DataFrame(rows), "{:.1f}"))

    # candidate choice by the pre-registered rule
    m3 = pd.read_csv(a.m3)
    m3 = m3[~m3.selector.str.contains("oracle|shuffled|always|VBS", regex=True)]
    m3 = m3[~m3.selector.isin(["D (always native)", "I- (validation-SBS)", "F- (always negative)"])]
    cands = [(r.selector + " (M3, out-of-fold)", r.PAR2) for r in m3.itertuples()]
    cands += [(k, v.mean()) for k, v in costs.items() if k in [s[0] for s in SCHEDULES.values()]]
    cands.sort(key=lambda x: x[1])
    out.append("\n\n## Pre-registered candidate choice (lowest dev PAR2 among deployable non-static policies)\n")
    out.append("| rank | policy | dev PAR2 |\n|---|---|---|")
    for i, (n, v) in enumerate(cands[:12]):
        out.append(f"| {i + 1} | {n} | {v:.2f} |")
    choice = cands[0]
    out.append(f"\n**Primary M5 candidate: {choice[0]}** (dev PAR2 {choice[1]:.2f}).\n")

    # figure
    order = t.sort_values("PAR2")
    fig, ax = plt.subplots(figsize=(6.6, 0.32 * len(order) + 1.0), dpi=150)
    yy = np.arange(len(order))[::-1]
    col = [fs.COLORS["Fminus"] if n.startswith("F−→") else fs.COLORS["D"] for n in order.policy]
    ax.barh(yy, order.PAR2, color=col, height=0.62)
    ax.set_yticks(yy)
    ax.set_yticklabels(order.policy, fontsize=7.5)
    ax.set_xlim(order.PAR2.min() * 0.95, order.PAR2.max() * 1.01)
    ax.set_xlabel("mean PAR2 over 817 dev instances (s); orange = F− prefix schedules")
    fs.style_axes(ax)
    fig.tight_layout()
    fig.savefig(os.path.join(a.out, "figures", "schedules_par2.png"))
    plt.close(fig)
    with open(os.path.join(a.out, "tables.md"), "w") as f:
        f.write("\n".join(out) + "\n")
    with open(os.path.join(a.out, "numbers.json"), "w") as f:
        json.dump({"table": t.to_dict(orient="records"), "candidates": cands, "choice": choice}, f, indent=1,
                  default=float)
    print("\n".join(out))


if __name__ == "__main__":
    main()
