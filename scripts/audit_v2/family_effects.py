#!/usr/bin/env python3
"""Audit v2, RQ1: complete per-family effects of every static / diagnostic
configuration and the early-negative schedules on the development set.

  scripts/audit_v2/family_effects.py --out reports/audit_v2/family_effects.md

Rows: all family groups of train+val (seed 0, T = 300 s).  For each
configuration: solved count and mean PAR2 per group; the last columns give the
log2 ratio of mean PAR2 to D for F-, I-, P- and F- -> D @1e4 (negative = better
than D; 0 when both are all-timeout).  Schedules that start with F- were run
only where the F- run reached K; elsewhere the schedule equals F- (identical
deterministic prefix), as in scripts/analyze_m4.py.
"""

import argparse
import os
import sys

import numpy as np
import pandas as pd

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "analysis"))
import fpstats as fs  # noqa: E402

T = 300.0
CFG = ["D", "Iminus", "Fminus", "Fplus", "D_noR", "Iminus_noR", "S_saved", "P_neg", "sw10k_Crev", "sw10k_CrevIn"]
SHORT = {"D": "D", "Iminus": "I−", "Fminus": "F−", "Fplus": "F+", "D_noR": "D/noR", "Iminus_noR": "I−/noR",
         "S_saved": "S", "P_neg": "P−", "sw10k_Crev": "F−→D", "sw10k_CrevIn": "F−→I−"}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    runs = pd.concat([fs.load_runs(p) for p in ("results/m2_census/runs.csv", "results/m2_diag/runs.csv",
                                                 "results/m3_replay/runs.csv", "results/m4/runs.csv")])
    runs = runs[runs.split.isin(["train", "val"]) & (runs.seed == 0) & (runs.variant == "orig")]
    runs = runs.drop_duplicates(["config", "instance"])
    w = runs.pivot_table(index="instance", columns="config", values="par2", aggfunc="first")
    for c in ("sw10k_Crev", "sw10k_CrevIn"):
        w[c] = w[c].fillna(w["Fminus"])
    w = w[CFG]
    meta = fs.instance_meta(runs).loc[w.index]
    rows = []
    for g, idx in meta.groupby("family_group").groups.items():
        sub = w.loc[idx]
        r = {"family group": g, "split": meta.loc[idx[0], "split"], "n": len(idx)}
        for c in CFG:
            r[f"{SHORT[c]} solved"] = int((sub[c] < 2 * T).sum())
        for c in CFG:
            r[f"{SHORT[c]} PAR2"] = sub[c].mean()
        for c in ("Fminus", "Iminus", "P_neg", "sw10k_Crev"):
            r[f"log2 {SHORT[c]}/D"] = float(np.log2(sub[c].mean() / sub["D"].mean()))
        rows.append(r)
    t = pd.DataFrame(rows).sort_values("log2 F−/D")
    tot = {"family group": "**all dev**", "split": "", "n": len(w)}
    for c in CFG:
        tot[f"{SHORT[c]} solved"] = int((w[c] < 2 * T).sum())
        tot[f"{SHORT[c]} PAR2"] = w[c].mean()
    for c in ("Fminus", "Iminus", "P_neg", "sw10k_Crev"):
        tot[f"log2 {SHORT[c]}/D"] = float(np.log2(w[c].mean() / w["D"].mean()))
    t = pd.concat([t, pd.DataFrame([tot])], ignore_index=True)
    n_better = {c: int((t[f"log2 {SHORT[c]}/D"].iloc[:-1] < -0.1).sum()) for c in ("Fminus", "Iminus", "P_neg", "sw10k_Crev")}
    n_worse = {c: int((t[f"log2 {SHORT[c]}/D"].iloc[:-1] > 0.1).sum()) for c in ("Fminus", "Iminus", "P_neg", "sw10k_Crev")}
    lines = ["# Per-family effects on the development set (generated by scripts/audit_v2/family_effects.py)\n",
             f"{len(t) - 1} family groups, {len(w)} instances (train+val, seed 0, T = 300 s). Configurations: "
             "D stock (0,1); I− initial negative (0,0); F− forced negative (1,0); F+ forced positive (1,1); "
             "D/noR and I−/noR with rephase=0; S pure saved (phase=0, target=0, rephase=0); P− decision-only "
             "negative (track P); F−→D and F−→I− forced negative for the first 1e4 conflicts, then native / "
             "initial-negative. Sorted by log2(PAR2 F− / PAR2 D); negative = better than D.\n",
             "Family groups with |log2 ratio| > 0.1 (better / worse than D): " +
             ", ".join(f"{SHORT[c]} {n_better[c]} / {n_worse[c]}" for c in n_better) + ".\n"]
    lines.append(fs.md_table(t, "{:.2f}"))
    with open(a.out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("\n".join(lines[:3]))


if __name__ == "__main__":
    main()
