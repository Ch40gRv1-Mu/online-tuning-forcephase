#!/usr/bin/env python3
"""Audit v2: Python vs C++ consistency of exported one-shot policies, and
timing sensitivity of policies that use CPU-time features.

  scripts/audit_v2/policy_consistency.py --dataset results/audit_v2/m3/dataset_strict.csv \
      --census results/m2_census/runs.csv --unit build/controller_unit --out reports/audit_v2/m3/policy_consistency.md

For each exported time-only policy (round 1 and audit v2 copies) the model is
refit in Python exactly as scripts/m3_train.py does (select_full on all dev
decision points) and its predict_proba is compared with the score that the
controller's own C++ parser/evaluator (tests/audit_v2/controller_unit.cpp
linked against build/fpc2) computes from the exported policy file, on
  (1) the logged checkpoint features of all dev decision points, and
  (2) the same rows with every feature set missing in turn (missing handling).
Timing sensitivity: the CPU-time feature r_time is scaled by 0.90/0.95/1.05/1.10
and the share of decision points whose action changes is reported (C++ scores).
"""

import argparse
import os
import re
import subprocess
import sys
import tempfile

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
import m3_train  # noqa: E402

POLICIES = [  # (file, direction, K)
    ("configs/policies/m3_oneshot_D_K1000_time.txt", "nat2neg", 1000),
    ("configs/policies/m3_oneshot_Iminus_K10000_time.txt", "in2neg", 10000),
    ("configs/policies/audit_v2/m3_oneshot_D_K1000_time.txt", "nat2neg", 1000),
    ("configs/policies/audit_v2/m3_oneshot_Iminus_K10000_time.txt", "in2neg", 10000),
]


def cpp_scores(unit, policy, X, cols):
    with tempfile.NamedTemporaryFile("w", suffix=".csv", delete=False) as f:
        f.write(",".join(cols) + "\n")
        for row in X:
            f.write(",".join("" if np.isnan(v) else repr(float(v)) for v in row) + "\n")
        path = f.name
    out = subprocess.run([unit, "eval", policy, path], capture_output=True, text=True, check=True).stdout
    os.unlink(path)
    return np.array([float(x) for x in out.split()])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dataset", required=True)
    ap.add_argument("--census", required=True)
    ap.add_argument("--unit", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    ds = pd.read_csv(a.dataset, dtype={"instance": str})
    census = pd.read_csv(a.census, dtype={"instance": str})
    census = census[census.split.isin(["train", "val"])]
    insts = np.array(sorted(census[census.config == "D"].instance.unique()))
    meta = census.drop_duplicates("instance").set_index("instance")
    groups = meta.loc[insts, "family_group"].values
    lines = ["# Exported one-shot policies: Python vs C++ and timing sensitivity "
             "(generated by scripts/audit_v2/policy_consistency.py)\n",
             "Python = scikit-learn model refit exactly as in scripts/m3_train.py (select_full on all dev rows); "
             "C++ = the controller's own policy parser and evaluator (build/controller_unit eval, linked against "
             "the fpc2 library) reading the exported file. Rows = dev decision points (logged checkpoint features).\n",
             "| policy | model | rows | max abs score diff | action disagreements | missing-value rows | "
             "missing: max diff / disagreements | switch share | action flips at r_time ×0.90 / ×0.95 / ×1.05 / ×1.10 |",
             "|---|---|---|---|---|---|---|---|---|"]
    for path, direction, K in POLICIES:
        text = open(path).read()
        cols = m3_train.FEATURE_SETS["time"]
        d = ds[(ds.direction == direction) & (ds.K == K) & (ds.track == "C")].set_index("instance").reindex(insts)
        has = ((d.has_decision == 1) & (d.alt_run == 1)).values
        cb = d.cost_base.values.astype(float)
        ca = np.where(has, d.cost_alt.values.astype(float), cb)
        y = (ca < cb).astype(int)
        w = np.where(has, np.abs(ca - cb), 0.0)
        X = d[["f_" + c for c in cols]].values.astype(float)
        (kind, params), _, model = m3_train.select_full(X, y, w, cb, ca, groups)
        rows = X[has]
        py = model.predict_proba(rows)[:, 1]
        cc = cpp_scores(a.unit, path, rows, cols)
        # missing-value handling: blank one feature at a time
        miss_rows, miss_py, miss_cc = [], [], []
        for j in range(len(cols)):
            Xm = rows.copy()
            Xm[:, j] = np.nan
            miss_rows.append(Xm)
        Xm = np.vstack(miss_rows)
        mp = model.predict_proba(Xm)[:, 1]
        mc = cpp_scores(a.unit, path, Xm, cols)
        flips = []
        for s in (0.90, 0.95, 1.05, 1.10):
            Xt = rows.copy()
            Xt[:, cols.index("r_time")] *= s
            flips.append(np.mean((cpp_scores(a.unit, path, Xt, cols) > 0.5) != (cc > 0.5)))
        mtype = re.search(r"model (\w+)", text).group(1)
        lines.append(f"| `{path}` | {mtype} ({kind} {params}) | {len(rows)} | {np.max(np.abs(py - cc)):.2e} | "
                     f"{int(np.sum((py > 0.5) != (cc > 0.5)))} | {len(Xm)} | {np.max(np.abs(mp - mc)):.2e} / "
                     f"{int(np.sum((mp > 0.5) != (mc > 0.5)))} | {np.mean(cc > 0.5):.3f} | "
                     + " / ".join(f"{100 * f:.1f}%" for f in flips) + " |")
    lines.append("\nNotes: scikit-learn trees compare float32-cast inputs with float32 thresholds while the C++ "
                 "evaluator uses doubles with the 9-digit printed thresholds; a disagreement could only occur for "
                 "inputs within float32 rounding of a threshold. All exported policies contain r_time (CPU seconds "
                 "to reach the prefix), so deployed decisions depend on measured time; the flip shares quantify that "
                 "dependence for realistic relative timing noise (M1: repeat-to-repeat p95 about 5–9%).\n")
    with open(a.out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
