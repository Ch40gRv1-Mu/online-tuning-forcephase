#!/usr/bin/env python3
"""Audit v2: compare round-1 and revised M3 selector tables (all pre-defined groups).

  scripts/audit_v2/m3_compare.py --round1 reports/m3/selectors.csv \
      --reproduced reports/audit_v2/m3/reproduce_round1/selectors.csv \
      --revised reports/audit_v2/m3/revised/selectors.csv --out reports/audit_v2/m3/comparison.md

Selectors whose feature sets never contained x_saved_flip_frac (time, C+R,
C+R+Q, C+R+T, static selectors, oracles, fixed rules) must reproduce the
round-1 numbers; differences are listed.  For the affected groups (C+R+P,
all, their shuffled-label controls) the round-1 and revised numbers are shown
side by side, together with the revised differences to D, I-, the static
selector, the time-only selector at the same K/prefix and the shuffled-label
control.  CIs are the 95% family-group cluster bootstrap intervals of the OOF
per-instance costs (as in round 1).
"""

import argparse
import re

import numpy as np
import pandas as pd

AFFECTED = re.compile(r"\[(C\+R\+P|all)\]")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--round1", required=True)
    ap.add_argument("--reproduced", required=True)
    ap.add_argument("--revised", required=True)
    ap.add_argument("--costs-revised", default="reports/audit_v2/m3/revised/oof_costs.csv")
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    r1 = pd.read_csv(a.round1).set_index("selector")
    rep = pd.read_csv(a.reproduced).set_index("selector")
    rv = pd.read_csv(a.revised).set_index("selector")
    lines = ["# M3 round 1 vs audit-v2 revision (generated by scripts/audit_v2/m3_compare.py)\n",
             "Revision = the only pre-specified change: x_saved_flip_frac removed from the P group and 'all' "
             "(docs/CORRECTION_PROTOCOL.md §5); same strict-gated data, outer folds (reports/m3/folds.csv), "
             "inner seeds, model grid, weights and bootstrap. PAR2 = mean out-of-fold deployed PAR2 over 817 dev "
             "instances; CIs: 95% family-group cluster bootstrap (10,000 resamples).\n"]
    num = ["PAR2", "solved", "red_vs_D_%", "CI_lo_%", "CI_hi_%", "red_vs_I-_%", "I-CI_lo_%", "I-CI_hi_%"]
    d = (r1[num] - rep.loc[r1.index, num]).abs().max().max()
    lines.append(f"Step (a): round-1 code on round-1 data reproduces reports/m3/selectors.csv for all {len(r1)} "
                 f"selectors (max absolute difference {d:.3g}).\n")
    unaffected = [s for s in r1.index if not AFFECTED.search(s)]
    diff = (r1.loc[unaffected, num] - rv.loc[unaffected, num]).abs().max(axis=1)
    lines.append(f"Selectors not using the flip feature: {len(unaffected)}; max absolute difference between round 1 "
                 f"and revision: {diff.max():.3g} (expected 0: identical data, folds and seeds).\n")
    if diff.max() > 1e-9:
        lines.append("| selector | max diff |\n|---|---|")
        for s, v in diff[diff > 1e-9].items():
            lines.append(f"| {s} | {v:.4g} |")
    aff = [s for s in r1.index if AFFECTED.search(s)]
    lines.append("\n## Affected selector groups: round 1 vs revised\n")
    lines.append("| selector | PAR2 r1 | PAR2 rev | solved r1 | solved rev | vs D r1 % | vs D rev % [CI] | "
                 "vs I− rev % [CI] | switched r1 | switched rev |")
    lines.append("|---|---|---|---|---|---|---|---|---|---|")
    for s in aff:
        x, y = r1.loc[s], rv.loc[s]
        lines.append(f"| {s} | {x.PAR2:.2f} | {y.PAR2:.2f} | {int(x.solved)} | {int(y.solved)} | "
                     f"{x['red_vs_D_%']:+.2f} | {y['red_vs_D_%']:+.2f} [{y['CI_lo_%']:+.2f}, {y['CI_hi_%']:+.2f}] | "
                     f"{y['red_vs_I-_%']:+.2f} [{y['I-CI_lo_%']:+.2f}, {y['I-CI_hi_%']:+.2f}] | "
                     f"{x.chose_alt:.0f} | {y.chose_alt:.0f} |")
    # revised differences to reference policies (paired, same instances)
    costs = pd.read_csv(a.costs_revised, index_col=0)
    lines.append("\n## Revised online selectors against reference policies (mean PAR2 difference, s; "
                 "negative = selector better)\n")
    lines.append("| selector | vs D | vs I− | vs static D/F− | vs time-only (same K, prefix) | vs own shuffled-label control |")
    lines.append("|---|---|---|---|---|---|")
    for s in rv.index:
        m = re.match(r"(I- prefix )?one-shot @K=(\d+) \[([^\]]+)\]$", s)
        if not m:
            continue
        pre, K, fs = m.group(1) or "", m.group(2), m.group(3)
        c = costs[s]
        t = costs.get(f"{pre}one-shot @K={K} [time]")
        sh = costs.get(f"{s} shuffled labels")
        lines.append(f"| {s} | {np.mean(c - costs['D (always native)']):+.2f} | "
                     f"{np.mean(c - costs['I- (validation-SBS)']):+.2f} | "
                     f"{np.mean(c - costs['static selector D/F- (cnffeatures)']):+.2f} | "
                     f"{'–' if t is None or fs == 'time' else f'{np.mean(c - t):+.2f}'} | "
                     f"{'–' if sh is None else f'{np.mean(c - sh):+.2f}'} |")
    best = rv[~rv.index.str.contains("oracle|shuffled|always|VBS")].PAR2.idxmin()
    lines.append(f"\nLowest revised OOF PAR2 among deployable selectors: **{best}** ({rv.loc[best, 'PAR2']:.2f}); "
                 f"D {rv.loc['D (always native)', 'PAR2']:.2f}, I− {rv.loc['I- (validation-SBS)', 'PAR2']:.2f}.\n")
    with open(a.out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
