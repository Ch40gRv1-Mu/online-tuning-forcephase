#!/usr/bin/env python3
"""Audit v2 P2: analysis of the low-noise overhead retest (docs/CORRECTION_PROTOCOL.md §6).

  scripts/audit_v2/analyze_retest.py --runs results/audit_v2/m1/runs.csv \
      --schedule results/audit_v2/m1/schedule.csv --list benchmarks/derived/audit_v2/m1_retest48.txt \
      --out reports/audit_v2/m1

Per instance and configuration the median CPU over the 6 repeats is used.
Slowdown = median_config / median_reference - 1.  Statistics over instances:
median and 95th percentile, each with a 95% instance-bootstrap interval
(10,000 resamples, seed 12345).  Repeat noise with the same aggregation: for
each configuration, median of repeats {0,2,4} vs median of {1,3,5}.
Instances with any timeout are listed separately (near-cutoff asymmetry)
and excluded from the ratio statistics only if some repeat timed out.
"""

import argparse
import json
import os
import sys

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "analysis"))
import fpstats as fs  # noqa: E402

NAMES = {"Dupstream": "upstream", "Doff": "patched-off (v1)", "D": "telemetry (v1)"}


def boot(values, stat, B=10000, seed=12345):
    v = np.asarray(values, float)
    rng = np.random.default_rng(seed)
    bs = np.array([stat(v[rng.integers(0, len(v), len(v))]) for _ in range(B)])
    return stat(v), np.percentile(bs, 2.5), np.percentile(bs, 97.5)


def p95(x):
    return np.percentile(x, 95)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", required=True)
    ap.add_argument("--schedule", required=True)
    ap.add_argument("--list", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    os.makedirs(os.path.join(a.out, "figures"), exist_ok=True)
    df = pd.read_csv(a.runs, dtype={"instance": str})
    sch = pd.read_csv(a.schedule, dtype={"instance": str})
    strata = {l.split()[0]: l.split()[1] for l in open(a.list) if l.strip() and not l.startswith("#")}
    out = ["# Overhead retest (audit v2, generated by scripts/audit_v2/analyze_retest.py)\n"]
    # schedule adherence: same core, start order as planned
    m = sch.merge(df[["run_id", "core", "host", "start_utc", "status", "cpu"]], on="run_id", suffixes=("_plan", ""))
    core_ok = (m.core_plan == m.core).all()
    order_ok = all((g.sort_values("position").start_utc.values == np.sort(g.start_utc.values)).all()
                   for _, g in m.groupby("instance"))
    out.append(f"Runs: {len(df)} (statuses {df.status.value_counts().to_dict()}); hosts {sorted(df.host.unique())}; "
               f"every run on its planned physical core: {core_ok}; per-instance execution order as planned: "
               f"{order_ok}. Configurations: upstream binary without telemetry, v1 patched binary with the "
               f"controller off, v1 telemetry-only (`--fpc=1`), all with LRAT proof output, T = 300 s.\n")
    # determinism
    st = df[df.status == "solved"].groupby("instance")[["conflicts", "decisions", "propagations"]].nunique()
    full = df.groupby("instance").status.apply(lambda s: (s == "solved").all())
    out.append(f"Search statistics identical across all 18 runs of an instance: "
               f"{int((st.loc[full[full].index] == 1).all(axis=1).sum())} of {int(full.sum())} fully solved instances.\n")
    to = df[df.status != "solved"].groupby(["instance", "config"]).size().unstack(fill_value=0)
    if len(to):
        out.append("Instances with timeouts (near cutoff; excluded from the ratio statistics):\n")
        out.append(fs.md_table(to.reset_index().assign(stratum=lambda x: x.instance.map(strata)), "{:.0f}"))
    ok = full[full].index
    med = df[df.instance.isin(ok)].pivot_table(index="instance", columns="config", values="cpu", aggfunc="median")
    rows = []
    ratios = {}
    for num, den in (("D", "Doff"), ("Doff", "Dupstream"), ("D", "Dupstream")):
        r = med[num] / med[den] - 1
        ratios[(num, den)] = r
        mm, mlo, mhi = boot(r, np.median)
        pp, plo, phi = boot(r, p95)
        rows.append({"comparison": f"{NAMES[num]} vs {NAMES[den]}", "instances": len(r),
                     "median %": 100 * mm, "median CI": f"[{100 * mlo:+.2f}, {100 * mhi:+.2f}]",
                     "p95 %": 100 * pp, "p95 CI": f"[{100 * plo:+.2f}, {100 * phi:+.2f}]",
                     "max %": 100 * r.max(), "aggregate %": 100 * (med[num].sum() / med[den].sum() - 1)})
    # repeat noise with the same aggregation
    for c in ("Dupstream", "Doff", "D"):
        x = df[df.instance.isin(ok) & (df.config == c)]
        even = x[x["repeat"] % 2 == 0].groupby("instance").cpu.median()
        odd = x[x["repeat"] % 2 == 1].groupby("instance").cpu.median()
        r = odd / even - 1
        mm, mlo, mhi = boot(r, np.median)
        pp, plo, phi = boot(r, p95)
        rows.append({"comparison": f"noise: {NAMES[c]}, median of odd vs even repeats", "instances": len(r),
                     "median %": 100 * mm, "median CI": f"[{100 * mlo:+.2f}, {100 * mhi:+.2f}]",
                     "p95 %": 100 * pp, "p95 CI": f"[{100 * plo:+.2f}, {100 * phi:+.2f}]",
                     "max %": 100 * r.max(), "aggregate %": np.nan})
    t = pd.DataFrame(rows)
    out.append("\n## Slowdown (per-instance median of 6 repeats; instance-bootstrap 95% CI)\n")
    out.append(fs.md_table(t, "{:.2f}"))
    # by stratum
    rows = []
    for s in ("Q1", "Q2", "Q3", "Q4"):
        ii = [i for i in med.index if strata[i] == s]
        r = ratios[("D", "Doff")].loc[ii]
        rows.append({"stratum": s, "instances": len(ii), "median upstream CPU s": med.loc[ii, "Dupstream"].median(),
                     "telemetry vs off median %": 100 * r.median(), "max %": 100 * r.max(),
                     "off vs upstream median %": 100 * ratios[("Doff", "Dupstream")].loc[ii].median()})
    out.append("\n\n## By stratum (round-1 upstream CPU quartiles)\n")
    out.append(fs.md_table(pd.DataFrame(rows), "{:.2f}"))
    # in-solver controller time
    tel = df[(df.config == "D") & df.hook_time.notna() & df.instance.isin(ok)]
    share = tel.hook_time / tel.cpu
    out.append(f"\n\nController hook time measured inside the solver (telemetry runs): median "
               f"{100 * share.median():.4f}%, p95 {100 * share.quantile(.95):.4f}%, max {100 * share.max():.4f}% of "
               f"run CPU. Not covered by hook_time: the always-on counters in `decide`/`analyze` (a few additions "
               f"per decision/conflict, present in both patched configurations) and, with the controller on, one "
               f"extra `native_phase_suggestion` query per free decision; their cost is part of the measured "
               f"telemetry-vs-off and off-vs-upstream differences.\n")
    passed = t.iloc[0]["p95 %"] <= 3.0
    out.append(f"\n**Target check (telemetry vs controller-off):** median {t.iloc[0]['median %']:+.2f}% "
               f"(target ≤ 1%), p95 {t.iloc[0]['p95 %']:+.2f}% {t.iloc[0]['p95 CI']} (target ≤ 3%): "
               f"{'p95 target met on this 48-instance sample' if passed else 'p95 target NOT demonstrated'}. "
               f"These are statements about this stratified 48-instance retest, not about the 292 instances of "
               f"round-1 M1.\n")
    fig, ax = plt.subplots(figsize=(6.0, 3.8), dpi=150)
    x = med["Dupstream"]
    ax.scatter(x, 100 * ratios[("D", "Doff")], s=14, color=fs.COLORS["D"], edgecolors="white", linewidths=0.4,
               label="telemetry vs controller-off")
    ax.scatter(x, 100 * ratios[("Doff", "Dupstream")], s=14, color=fs.COLORS["Fminus"], edgecolors="white",
               linewidths=0.4, label="controller-off vs upstream")
    ax.axhline(0, color=fs.INK2, linewidth=0.8)
    ax.set_xscale("log")
    ax.set_xlabel("upstream CPU s (median of 6)")
    ax.set_ylabel("slowdown %")
    ax.set_title("Overhead retest: 48 instances × 6 repeats, low concurrency", fontsize=10)
    fs.style_axes(ax)
    ax.legend(fontsize=7, frameon=False)
    fig.tight_layout()
    fig.savefig(os.path.join(a.out, "figures", "overhead_retest.png"))
    plt.close(fig)
    with open(os.path.join(a.out, "retest.md"), "w") as f:
        f.write("\n".join(out) + "\n")
    t.to_csv(os.path.join(a.out, "retest_table.csv"), index=False)
    print("\n".join(out))


if __name__ == "__main__":
    main()
