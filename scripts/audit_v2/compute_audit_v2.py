#!/usr/bin/env python3
"""Audit v2 compute ledger (budget: 100 CPU core-hours for this round).

  scripts/audit_v2/compute_audit_v2.py --out reports/audit_v2/COMPUTE_AUDIT_V2.md

Solver and checker CPU of the overhead retest are summed from the immutable run
records (campaign audit_v2_m1_retest).  Every other item is a measured CPU time
(rusage of the step) or, where only wall time and allocation are known, an
upper bound = processes x wall time.  Slurm accounting (sacct TotalCPU) does
not record CPU of container steps on this cluster, so it is not used.
"""

import argparse
import glob
import json
import os

DATA = os.environ.get("FP_DATA", "/mnt/data/zhaofeng/projects/workspace/online-tuning-forcephase")

OTHER = [  # (item, CPU seconds, basis)
    ("evidence snapshot", 5, "measured (approx.)"),
    ("strict M3 gate build, 3 executions", 330, "measured, ~110 s each"),
    ("gate regression tests", 5, "measured"),
    ("ledger-wide integrity audit (36,077 runs, 1,325 CNF hashes)", 311, "measured rusage"),
    ("fpc2 builds on host (2 builds, 24 jobs, ~60 s each)", 2880, "upper bound 2 x 24 x 60 s"),
    ("fpc2/fpc2-check container build + unit/API tests (job 727435)", 1216, "upper bound 32 CPUs x 38 s"),
    ("v2 integration test, attempt 1 (job 727436, interrupted after 9 min 45 s, no result)", 11700,
     "upper bound 20 processes x 585 s"),
    ("v2 integration test, attempt 2 (job 729353, conflict limit 1e5)", 1495, "measured rusage"),
    ("M0 suite on fpc2/fpc2-check (job 729379)", 1440, "upper bound 32 processes x 45 s"),
    ("M3 reproduce round 1", 490, "measured (user+sys)"),
    ("M3 revised", 470, "measured (user+sys)"),
    ("M3 comparison, feature signal, policy consistency", 120, "measured (approx.)"),
    ("overhead retest analysis", 30, "measured (approx.)"),
    ("M5 independent recheck", 22, "measured"),
    ("family effects, ablation pairs", 70, "measured (approx.)"),
    ("clean-clone reproduction chain (job 729372: builds, M0 quick, smoke 80 runs, revised M3)", 2057,
     "measured rusage"),
]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    solver = checker = 0.0
    n = 0
    for p in glob.glob(os.path.join(DATA, "runs", "results", "*", "*.json")):
        with open(p) as f:
            r = json.load(f)
        if r["key"].get("campaign") == "audit_v2_m1_retest":
            n += 1
            solver += r["cpu"]
            checker += r["verification"].get("cpu", 0) or 0
    rows = [("overhead retest: solver CPU of %d runs (incl. LRAT output)" % n, solver, "sum over run records"),
            ("overhead retest: model/proof checking", checker, "sum over run records")] + OTHER
    total = sum(r[1] for r in rows)
    lines = ["# Audit v2 compute ledger (generated by scripts/audit_v2/compute_audit_v2.py)\n",
             "Budget for this round: 100 CPU core-hours (docs/AGENT_GOAL.md v2). Round-1 compute is unchanged in "
             "[../COMPUTE_LEDGER.md](../COMPUTE_LEDGER.md). Upper bounds are used where only allocation × wall time "
             "is known (sacct does not record CPU of container steps here). The exclusive node of the overhead "
             "retest was allocated for 1 h 19 min (192 logical CPUs) but ran only 16 solver processes by design.\n",
             "| item | CPU hours | basis |", "|---|---|---|"]
    for item, sec, basis in rows:
        lines.append(f"| {item} | {sec / 3600:.2f} | {basis} |")
    lines.append(f"| **total (with upper bounds)** | **{total / 3600:.1f}** | of 100 budgeted |")
    lines.append("\nNo resources were purchased; no failed record was deleted. The interrupted first integration test "
                 "produced no result file; it is counted with its upper bound.\n")
    with open(a.out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
