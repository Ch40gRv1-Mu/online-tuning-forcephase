#!/usr/bin/env python3
"""Audit v2: independent recomputation of the frozen M5 results (no solver re-runs).

  scripts/audit_v2/m5_recheck.py --out reports/audit_v2/m5_recheck.md

Written independently of scripts/m5_eval.py and scripts/collect.py: reads the
immutable JSON run records under $FP_DATA/runs/results directly (records whose
'exp' is m5_heldout), the manifest, the static features and the frozen files,
and recomputes coverage, statuses, PAR2, solved per seed, the derived static
selector and random-switching-time baselines, and relative PAR2 reductions with
a separately coded family-cluster bootstrap.  Compares with
reports/m5/numbers.json (points must agree to 1e-9; bootstrap bounds within
Monte-Carlo tolerance) and checks that the freeze commit precedes every M5 run.
"""

import argparse
import csv
import glob
import hashlib
import json
import os
import subprocess
from collections import defaultdict

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DATA = os.environ.get("FP_DATA", "/mnt/data/zhaofeng/projects/workspace/online-tuning-forcephase")


def tree_or_linear(model, x):
    feats = model["features"]
    if model["kind"] == "tree":
        n = model["nodes"]
        i = 0
        while n[i]["left"] != -1:
            v = x[feats.index(n[i]["feature"])]
            left = n[i]["missing_left"] if v != v else v <= n[i]["threshold"]
            i = n[i]["left"] if left else n[i]["right"]
        return n[i]["value"]
    z = model["bias"]
    for t, v in zip(model["terms"], x):
        v = t["impute"] if v != v else v
        z += t["weight"] * (v - t["mean"]) / t["scale"]
    return 1.0 / (1.0 + np.exp(-z))


def cluster_boot(base, cand, groups, B=10000, seed=2027):
    ug = sorted(set(groups))
    idx = {g: [i for i, h in enumerate(groups) if h == g] for g in ug}
    rng = np.random.default_rng(seed)
    out = []
    for _ in range(B):
        sel = [idx[ug[k]] for k in rng.integers(0, len(ug), len(ug))]
        ii = [i for s in sel for i in s]
        out.append(1 - cand[ii].sum() / base[ii].sum())
    return np.percentile(out, [2.5, 97.5])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    fz = json.load(open(os.path.join(ROOT, "configs", "m5_freeze.json")))
    exp = json.load(open(os.path.join(ROOT, "configs", "experiments", "m5_heldout.json")))
    man = {r["hash"]: r for r in csv.DictReader(open(os.path.join(ROOT, "benchmarks", "manifest.csv")))}
    static = {r["instance"]: r for r in csv.DictReader(open(os.path.join(ROOT, "results",
                                                                          "static_features_heldout.csv")))}
    recs = []
    for p in glob.glob(os.path.join(DATA, "runs", "results", "*", "*.json")):
        with open(p) as f:
            r = json.load(f)
        if r["exp"] == "m5_heldout":
            recs.append(r)
    T = float(exp["timeout"])
    lines = ["# Independent recomputation of the frozen M5 results (generated by scripts/audit_v2/m5_recheck.py)\n",
             "Re-analysis of the existing run records only; no solver was re-run.\n"]
    # coverage
    insts = sorted(h for h, r in man.items() if r["split"] in ("test", "t2026"))
    cell = defaultdict(list)
    for r in recs:
        cell[(r["config"], r["key"]["instance"], r["key"]["seed"])].append(r)
    expected = [(c, h, s) for c in exp["configs"] for h in insts for s in exp["seeds"]]
    missing = [k for k in expected if k not in cell]
    dup = [k for k, v in cell.items() if len(v) > 1]
    extra = [k for k in cell if k not in set(expected)]
    status = defaultdict(int)
    bad = 0
    for r in recs:
        status[r["status"]] += 1
        if r["status"] == "solved" and not (r["verification"].get("ok") is True and r["cpu"] <= T):
            bad += 1
    lines.append(f"Records: {len(recs)}; expected cells {len(expected)} (configs × {len(insts)} instances × seeds "
                 f"{exp['seeds']}); missing {len(missing)}, duplicated {len(dup)}, unexpected {len(extra)}; "
                 f"statuses {dict(status)}; solved records without a passing verification or over T: {bad}.\n")
    # freeze precedence
    tag_time = subprocess.run(["git", "-C", ROOT, "log", "-1", "--format=%cI", "m5-freeze"], capture_output=True,
                              text=True).stdout.strip()
    tag_utc = subprocess.run(["date", "-u", "-d", tag_time, "+%Y-%m-%dT%H:%M:%SZ"], capture_output=True,
                             text=True).stdout.strip()
    first = min(r["start_utc"] for r in recs)
    lines.append(f"Freeze commit (tag m5-freeze) committed {tag_utc}; first M5 run started {first}; "
                 f"freeze precedes all M5 runs: {tag_utc < first}.\n")
    # cost tables
    cost = {}
    solved = {}
    cpu = {}
    for (c, h, s), v in cell.items():
        r = v[0]
        ok = r["status"] == "solved"
        cost[(c, h, s)] = r["cpu"] if ok else 2 * T
        solved[(c, h, s)] = ok
        cpu[(c, h, s)] = r["cpu"]
    seeds = exp["seeds"]
    names = dict(fz["config_names"])
    names[fz["primary"]["config"]] = fz["primary"]["name"]
    policies = {names.get(c, c): c for c in exp["configs"]}
    # derived: static selector
    model = json.load(open(os.path.join(ROOT, fz["static_selector"]["model_file"])))
    for h in insts:
        x = [float(static[h][f]) if static[h][f] not in ("", "nan") else float("nan") for f in model["features"]]
        pick = model["b"] if tree_or_linear(model, x) > 0.5 else model["a"]
        fc = float(static[h]["cpu_time"])
        for s in seeds:
            ok = solved[(pick, h, s)] and cpu[(pick, h, s)] + fc <= T
            cost[("SS", h, s)] = cpu[(pick, h, s)] + fc if ok else 2 * T
            solved[("SS", h, s)] = ok
    policies[fz["static_selector"]["name"]] = "SS"
    rs = fz["random_switch_time"]
    for h in insts:
        for s in seeds:
            k = int(hashlib.sha256(f"{h}:{s}:{rs['salt']}".encode()).hexdigest()[:15], 16) % len(rs["branches"])
            b = rs["branches"][k]
            cost[("RS", h, s)], solved[("RS", h, s)] = cost[(b, h, s)], solved[(b, h, s)]
    policies[rs["name"]] = "RS"
    ref = json.load(open(os.path.join(ROOT, "reports", "m5", "numbers.json")))
    lines.append("| test set | policy | PAR2 (recheck) | PAR2 (report) | solved/seed (recheck) | Δ vs I− % recheck [CI] | "
                 "report [CI] | Δ vs D % recheck | report |")
    lines.append("|---|---|---|---|---|---|---|---|---|")
    maxdiff, maxci = 0.0, 0.0
    for tset, sel in (("test (family-disjoint)", lambda r: r["split"] == "test"),
                      ("t2026 (temporal)", lambda r: r["split"] == "t2026")):
        hs = [h for h in insts if sel(man[h])]
        groups = [man[h]["family_group"] for h in hs]
        per = {p: np.array([np.mean([cost[(c, h, s)] for s in seeds]) for h in hs]) for p, c in policies.items()}
        rep = {r["policy"]: r for r in ref[tset]}
        for p in rep:
            if p not in per:
                continue
            v = per[p]
            sv = " / ".join(str(sum(solved[(policies[p], h, s)] for h in hs)) for s in seeds)
            dI = 100 * (1 - v.sum() / per[fz["sbs_name"]].sum())
            dD = 100 * (1 - v.sum() / per["D (stock)"].sum())
            lo, hi = 100 * cluster_boot(per[fz["sbs_name"]], v, groups)
            r = rep[p]
            maxdiff = max(maxdiff, abs(v.mean() - r["PAR2"]), abs(dI - r["red vs SBS %"]), abs(dD - r["red vs D %"]))
            if p != fz["sbs_name"]:
                maxci = max(maxci, abs(lo - r["CI lo"]), abs(hi - r["CI hi"]))
            ok_sv = sv == r["solved/seed"]
            lines.append(f"| {tset} | {p} | {v.mean():.4f} | {r['PAR2']:.4f} | {sv}{'' if ok_sv else ' ≠ ' + r['solved/seed']} | "
                         f"{dI:+.2f} [{lo:+.2f}, {hi:+.2f}] | {r['red vs SBS %']:+.2f} [{r['CI lo']:+.2f}, {r['CI hi']:+.2f}] | "
                         f"{dD:+.2f} | {r['red vs D %']:+.2f} |")
    lines.append(f"\nMaximum absolute difference of point estimates (PAR2 and relative reductions): {maxdiff:.2e}; "
                 f"maximum difference of bootstrap bounds (independent resampling stream, B = 10,000): "
                 f"{maxci:.2f} percentage points.\n")
    with open(a.out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
