#!/usr/bin/env python3
"""Audit v2, RQ4: matched ablation pairs on the development set.

  scripts/audit_v2/ablation_pairs.py --out reports/audit_v2/ablation_pairs.md

Only pairs of configurations whose options differ in a single, named factor
are compared (factor definitions from the pinned source; see
docs/SOURCE_AUDIT.md and docs/DESIGN.md).  For each pair: relative mean-PAR2
change (positive = second configuration better) with a 95% family-group
cluster bootstrap CI, and changes of solved counts in the post-hoc SAT /
UNSAT strata (observed answers; descriptive only).
"""

import argparse
import os
import sys

import numpy as np
import pandas as pd

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "analysis"))
import fpstats as fs  # noqa: E402

T = 300.0
PAIRS = [
    ("D", "Iminus", "phase option 1→0 only: saved initial sign, fallback sign and the direction of "
                    "'original'/'inverted' rephasing (rephase, target unchanged)"),
    ("D", "D_noR", "rephase 1→0 only: no rephasing and therefore no rephase-triggered local search (walk) "
                   "or warmup; target phases unchanged"),
    ("D_noR", "Iminus_noR", "phase option 1→0 with rephasing off: saved initial sign and fallback only"),
    ("Iminus_noR", "Fminus", "forcephase 0→1 (rephase already off in both, negative initial phase in both): "
                             "free decisions use the forced negative sign instead of target/saved phases; also "
                             "likely_phase (clause layout in garbage collection)"),
    ("Iminus_noR", "S_saved", "target 1→0 only (rephase off, negative initial phase): stable-mode decisions use "
                              "saved instead of target phases"),
    ("D", "P_neg", "track P: free decisions forced negative, everything else native (rephasing and walk still "
                   "run but cannot influence free decisions)"),
    ("Fplus", "Fminus", "sign of the forced phase (both force and disable rephasing); interacts with the encoding"),
    ("P_neg", "Fminus", "decision-only negative vs forcephase negative: F− additionally disables rephasing/walk, "
                        "initialises saved negative and changes likely_phase"),
]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    runs = pd.concat([fs.load_runs("results/m2_census/runs.csv"), fs.load_runs("results/m2_diag/runs.csv")])
    runs = runs[runs.split.isin(["train", "val"])]
    w = fs.wide_cost(runs)
    meta = fs.instance_meta(runs).loc[w.index]
    ans, _ = fs.observed_answer(runs)
    stratum = pd.Series("unsolved", index=w.index)
    stratum.loc[stratum.index.intersection(ans.index)] = ans
    g = meta.family_group.values
    lines = ["# Matched ablation pairs, development set (generated by scripts/audit_v2/ablation_pairs.py)\n",
             f"{len(w)} dev instances (train+val), seed 0, T = 300 s. 'Δ PAR2' = 1 − PAR2(second)/PAR2(first), "
             "positive = second configuration better, 95% family-group cluster bootstrap CI (10,000). SAT/UNSAT = "
             f"post-hoc observed answers ({int((stratum == 'SAT').sum())} SAT, {int((stratum == 'UNSAT').sum())} "
             "UNSAT, the rest unsolved by every configuration); descriptive only.\n",
             "| first → second | single factor changed | Δ PAR2 % [CI] | Δ solved SAT | Δ solved UNSAT |",
             "|---|---|---|---|---|"]
    for x, y, factor in PAIRS:
        p, lo, hi = fs.paired_relative_ci(w[x].values, w[y].values, g)
        ds = int(((w[y] < 2 * T) & (stratum == "SAT")).sum() - ((w[x] < 2 * T) & (stratum == "SAT")).sum())
        du = int(((w[y] < 2 * T) & (stratum == "UNSAT")).sum() - ((w[x] < 2 * T) & (stratum == "UNSAT")).sum())
        lines.append(f"| {fs.LABELS.get(x, x)} → {fs.LABELS.get(y, y)} | {factor} | {100 * p:+.1f} "
                     f"[{100 * lo:+.1f}, {100 * hi:+.1f}] | {ds:+d} | {du:+d} |")
    lines.append("\nPath reading (not a unique decomposition; interactions were not tested): D → D/no-R → I−/no-R "
                 "→ F− changes SAT solved by the amounts in rows 2, 3 and 4; the order of steps is a choice, and "
                 "other orders (e.g. D → I− first) give other per-step attributions.\n")
    with open(a.out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
