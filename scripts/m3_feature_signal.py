#!/usr/bin/env python3
"""Exploratory: univariate signal of prefix features for the same-state switch benefit.

  scripts/m3_feature_signal.py --dataset results/m3/dataset.csv --out reports/m3/feature_signal.md

For each K (D prefix -> F-), on decision points whose two branches are not
both timeouts: Spearman correlation of each checkpoint feature with
y = log2(cost switch / cost stay) over all instances, and after removing
family-group means of both feature and y (within-family signal, which is
what a family-disjoint model has to exploit).  Descriptive only; the
predictive test is the grouped CV in m3_train.py.  Also: share of instances
where switching is better, by post-hoc observed answer.
"""

import argparse
import os
import sys

import numpy as np
import pandas as pd
from scipy.stats import spearmanr

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "analysis"))
import fpstats as fs  # noqa: E402

T = 300.0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dataset", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    ds = pd.read_csv(a.dataset, dtype={"instance": str})
    out = ["# Univariate feature signal for the same-state switch benefit (exploratory; generated by "
           "scripts/m3_feature_signal.py)\n",
           "y = log2(PAR2 after switching to F− at K / PAR2 staying NATIVE) on decision points that are not "
           "censored on both sides; negative y = switching helps. ρ: Spearman over instances; ρ_within: after "
           "subtracting family-group means from feature and y.\n"]
    feats = [c for c in ds.columns if c.startswith("f_") and c not in ("f_r_action", "f_r_switches")]
    for K in sorted(ds[ds.direction == "nat2neg"].K.unique()):
        d = ds[(ds.direction == "nat2neg") & (ds.K == K) & (ds.track == "C") & (ds.has_decision == 1) &
               (ds.alt_run == 1)].copy()
        d = d[~((d.cost_base >= 2 * T) & (d.cost_alt >= 2 * T))]
        d["y"] = np.log2(d.cost_alt / d.cost_base)
        rows = []
        for f in feats:
            x = d[f].astype(float)
            m = x.notna()
            if m.sum() < 30 or x[m].nunique() < 3:
                continue
            r, _ = spearmanr(x[m], d.y[m])
            xd = x[m] - x[m].groupby(d.family_group[m]).transform("mean")
            yd = d.y[m] - d.y[m].groupby(d.family_group[m]).transform("mean")
            rw, _ = spearmanr(xd, yd) if xd.nunique() > 2 else (np.nan, None)
            rows.append({"feature": f[2:], "n": int(m.sum()), "rho": r, "rho_within": rw})
        t = pd.DataFrame(rows).sort_values("rho", key=lambda s: -s.abs())
        out.append(f"\n## K = {K}: {len(d)} uncensored decision points, {d.family_group.nunique()} family groups; "
                   f"switch better on {(d.y < 0).sum()}, stay better on {(d.y > 0).sum()}\n")
        out.append(fs.md_table(t.head(12), "{:.2f}"))
        by = d.groupby(d.result_base.fillna(d.result_alt).fillna("unsolved"))["y"].agg(
            n="size", switch_better=lambda s: (s < 0).mean(), median_y="median")
        out.append("\n\nBy observed answer (post hoc):\n")
        out.append(fs.md_table(by.reset_index(), "{:.2f}"))
    with open(a.out, "w") as f:
        f.write("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
