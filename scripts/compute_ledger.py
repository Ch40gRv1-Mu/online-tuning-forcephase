#!/usr/bin/env python3
"""Compute ledger over all attempts (stdlib only).

  scripts/compute_ledger.py --out reports/COMPUTE_LEDGER.md

Sums, per experiment, solver CPU and checker CPU of completed runs (from the
immutable result records) and counts every attempt in
$FP_DATA/runs/attempts/*.jsonl, including interrupted attempts (start
without done) and runner errors, so that the cost of all tries is visible.
Slurm allocation (node-hours) is taken from `sacct` for the job ids listed in
the attempt logs when sacct is available.
"""

import argparse
import collections
import glob
import json
import os
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fprun  # noqa: E402


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    att_dir = os.path.join(fprun.DATA, "runs", "attempts")
    starts, dones, errors = collections.Counter(), collections.Counter(), collections.Counter()
    jobs = set()
    for p in glob.glob(os.path.join(att_dir, "*.jsonl")):
        exp = os.path.basename(p).split("-cpu-")[0]
        for line in open(p):
            try:
                x = json.loads(line)
            except json.JSONDecodeError:
                continue
            ev = x.get("event")
            if ev == "start":
                starts[exp] += 1
                if x.get("slurm_job"):
                    jobs.add(x["slurm_job"].split("_")[0])
            elif ev == "done":
                dones[exp] += 1
            elif ev == "runner-error":
                errors[exp] += 1
    # completed results by experiment (first experiment that created the record)
    solver, checker, nruns, status = collections.Counter(), collections.Counter(), collections.Counter(), {}
    for p in glob.glob(os.path.join(fprun.DATA, "runs", "results", "*", "*.json")):
        r = json.load(open(p))
        e = r["exp"]
        solver[e] += r["cpu"]
        checker[e] += r["verification"].get("cpu", 0) or 0
        nruns[e] += 1
        status.setdefault(e, collections.Counter())[r["status"]] += 1
    lines = ["# Compute ledger (generated by scripts/compute_ledger.py)\n",
             "Solver CPU = user+sys CPU of solver processes incl. LRAT proof output; checker CPU = model checks and "
             "lrat-trim. Attempts include runs interrupted by preemption or cancellation (start without done).\n",
             "| experiment | result records | statuses | solver CPU h | checker CPU h |",
             "|---|---|---|---|---|"]
    for e in sorted(nruns):
        st = ", ".join(f"{k} {v}" for k, v in sorted(status[e].items()))
        lines.append(f"| {e} | {nruns[e]} | {st} | {solver[e] / 3600:.1f} | {checker[e] / 3600:.2f} |")
    lines.append(f"| **total** | {sum(nruns.values())} | | {sum(solver.values()) / 3600:.1f} | "
                 f"{sum(checker.values()) / 3600:.2f} |\n")
    lines += ["| attempt log (job name) | starts | done | runner errors | interrupted |", "|---|---|---|---|---|"]
    for e in sorted(starts):
        lines.append(f"| {e} | {starts[e]} | {dones[e]} | {errors[e]} | {starts[e] - dones[e] - errors[e]} |")
    node_h = None
    if jobs:
        try:
            out = subprocess.run(["sacct", "-n", "-X", "-P", "-j", ",".join(sorted(jobs)),
                                  "--format=JobID,ElapsedRaw,AllocCPUS"], capture_output=True, text=True).stdout
            secs = sum(int(l.split("|")[1]) for l in out.splitlines() if l.split("|")[1].isdigit())
            cpus = sum(int(l.split("|")[1]) * int(l.split("|")[2]) for l in out.splitlines()
                       if l.split("|")[1].isdigit() and l.split("|")[2].isdigit())
            node_h = (secs / 3600, cpus / 3600)
        except (OSError, IndexError, ValueError):
            pass
    if node_h:
        lines.append(f"\nSlurm allocations of these jobs: {node_h[0]:.1f} node-hours "
                     f"({node_h[1]:.0f} allocated logical-CPU-hours; exclusive nodes, 48 solver processes per "
                     f"192-CPU node).\n")
    lines.append("\nOther compute not in the ledger: builds, M0 suite (< 1 CPU-h), static feature extraction "
                 "(seconds per instance, recorded per instance in results/static_features_*.csv), model training "
                 "(minutes on one core).\n")
    with open(a.out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
