#!/usr/bin/env python3
"""M1 analysis: telemetry/patch overhead and search determinism.

  scripts/analyze_m1.py --runs results/m1_overhead/runs.csv --out reports/m1

Configurations: Dupstream (unpatched binary, no telemetry), Doff (patched,
controller off), D (patched, telemetry --fpc=1), each with repeats 0..2 on the
same instances, all with LRAT proof output (as in every experiment).
"""

import argparse
import json
import os
import sys

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "analysis"))
import fpstats as fs  # noqa: E402


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    os.makedirs(os.path.join(a.out, "figures"), exist_ok=True)
    df = fs.load_runs(a.runs)
    configs = ["Dupstream", "Doff", "D"]
    df = df[df.config.isin(configs)]
    out = ["# M1 tables (generated by scripts/analyze_m1.py)\n"]
    nums = {}
    out.append(f"Runs: {len(df)}; status counts: {df.status.value_counts().to_dict()}\n")

    # determinism of search statistics for solved runs
    solved = df[df.status == "solved"]
    keys = ["conflicts", "decisions", "propagations", "restarts", "rephased"]
    g = solved.groupby("instance")[keys].nunique()
    allsolved = solved.groupby("instance").size()
    n_expected = df.groupby("instance").size()
    full = allsolved[allsolved == n_expected.loc[allsolved.index]].index
    mism = g.loc[full][(g.loc[full] > 1).any(axis=1)]
    out.append(f"\n## Determinism\n\nInstances solved in all {len(configs)}×repeats runs: {len(full)}. "
               f"Instances where any of {keys} differs between upstream / controller-off / telemetry or "
               f"between repeats: **{len(mism)}**.\n")
    answers = solved.groupby("instance").result.nunique()
    out.append(f"Instances with more than one answer: {(answers > 1).sum()}.\n")
    nums["determinism_instances"] = int(len(full))
    nums["determinism_mismatches"] = int(len(mism))

    # overhead on instances solved by all runs, baseline >= 1 s
    med = df[df.instance.isin(full)].pivot_table(index="instance", columns="config", values="cpu", aggfunc="median")
    med = med[med["Dupstream"] >= 1.0]
    rows = []
    for num, den, label in (("D", "Doff", "telemetry vs controller-off"),
                            ("Doff", "Dupstream", "patched-off vs upstream"),
                            ("D", "Dupstream", "telemetry vs upstream")):
        r = med[num] / med[den] - 1
        rows.append({"comparison": label, "instances": len(r), "median_slowdown_%": 100 * r.median(),
                     "p95_slowdown_%": 100 * r.quantile(0.95), "mean_slowdown_%": 100 * r.mean(),
                     "aggregate_%": 100 * (med[num].sum() / med[den].sum() - 1)})
    # noise floor: same config, repeat-to-repeat
    rep = df[df.instance.isin(med.index)].pivot_table(index=["instance", "config"], columns="repeat",
                                                      values="cpu", aggfunc="first")
    if 0 in rep and 1 in rep:
        r = (rep[1] / rep[0] - 1).dropna()
        rows.append({"comparison": "same config, repeat 1 vs 0 (noise)", "instances": len(r),
                     "median_slowdown_%": 100 * r.median(), "p95_slowdown_%": 100 * r.quantile(0.95),
                     "mean_slowdown_%": 100 * r.mean(), "aggregate_%": float("nan")})
        rows.append({"comparison": "same config, |repeat 1 vs 0| (noise)", "instances": len(r),
                     "median_slowdown_%": 100 * r.abs().median(), "p95_slowdown_%": 100 * r.abs().quantile(0.95),
                     "mean_slowdown_%": 100 * r.abs().mean(), "aggregate_%": float("nan")})
    t = pd.DataFrame(rows)
    out.append("\n## Overhead (per-instance median CPU over 3 repeats; instances solved by all runs, upstream ≥ 1 s)\n")
    out.append(fs.md_table(t, "{:.2f}"))
    nums["overhead"] = rows

    # direct controller time
    d = df[(df.config == "D") & df.hook_time.notna()]
    frac = d.hook_time / d.cpu.clip(lower=1e-9)
    out.append(f"\n\nController hook time (measured inside the solver) as share of run CPU: median "
               f"{100 * frac.median():.4f}%, p95 {100 * frac.quantile(0.95):.4f}%, max {100 * frac.max():.4f}%.\n")
    nums["hook_share_median"] = float(frac.median())
    nums["hook_share_p95"] = float(frac.quantile(0.95))

    # figure: per-instance slowdown vs runtime
    fig, ax = plt.subplots(figsize=(6.0, 3.8), dpi=150)
    x = med["Dupstream"]
    ax.scatter(x, 100 * (med["D"] / med["Doff"] - 1), s=12, color=fs.COLORS["D"], edgecolors="white",
               linewidths=0.4, label="telemetry vs controller-off")
    ax.scatter(x, 100 * (med["Doff"] / med["Dupstream"] - 1), s=12, color=fs.COLORS["Fminus"],
               edgecolors="white", linewidths=0.4, label="controller-off vs upstream")
    ax.axhline(0, color=fs.INK2, linewidth=0.8)
    ax.set_xscale("log")
    ax.set_xlabel("upstream CPU s (median of 3)")
    ax.set_ylabel("slowdown %")
    fs.style_axes(ax)
    ax.legend(fontsize=7, frameon=False)
    ax.set_title("Per-instance overhead (median of 3 repeats)", fontsize=10)
    fig.tight_layout()
    fig.savefig(os.path.join(a.out, "figures", "overhead.png"))
    plt.close(fig)
    with open(os.path.join(a.out, "tables.md"), "w") as f:
        f.write("\n".join(out) + "\n")
    with open(os.path.join(a.out, "numbers.json"), "w") as f:
        json.dump(nums, f, indent=1, default=float)
    print("\n".join(out))


if __name__ == "__main__":
    main()
