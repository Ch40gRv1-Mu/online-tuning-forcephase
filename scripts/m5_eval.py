#!/usr/bin/env python3
"""M5 frozen held-out evaluation (run once, after configs/m5_freeze.json is committed).

  scripts/m5_eval.py --freeze configs/m5_freeze.json --runs results/m5/runs.csv \
      --static results/static_features_test.csv --out reports/m5

The freeze file names the unique primary candidate, the validation-SBS, the
static baselines, deployable online baselines, and derived selectors that are
evaluated from deterministic branch runs (static selector: chosen static run
+ feature CPU time; random one-shot: per (instance, seed) coin with the frozen
probability choosing between the base run and the switch-at-K run).
Per-instance cost = mean PAR2 over seeds; primary statistic = relative mean
PAR2 reduction of the candidate vs the SBS with a 95% paired family-group
cluster bootstrap (10,000 resamples); solved counts are reported per seed.
Each test set (family-disjoint 'test', temporal 't2026') is analysed
separately; t2026 is further split by temporal tag (seen/devtest/new).
"""

import argparse
import hashlib
import json
import os
import sys

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "analysis"))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fpstats as fs  # noqa: E402
from m3_train import eval_json  # noqa: E402


def coin(instance, seed, salt, p):
    h = hashlib.sha256(f"{instance}:{seed}:{salt}".encode()).hexdigest()
    return int(h[:15], 16) / float(16 ** 15) < p


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--freeze", required=True)
    ap.add_argument("--runs", required=True)
    ap.add_argument("--static", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    fz = json.load(open(a.freeze))
    T = float(fz["T"])
    df = fs.load_runs(a.runs)
    static = pd.read_csv(a.static, dtype={"instance": str}).set_index("instance")
    os.makedirs(os.path.join(a.out, "figures"), exist_ok=True)
    out = [f"# M5 held-out evaluation (generated by scripts/m5_eval.py from {a.runs})\n",
           f"Freeze file: `{a.freeze}` (commit recorded in it). T = {T:.0f} s CPU. Seeds: {fz['seeds']}.\n"]
    status_counts = df.groupby("config").status.value_counts().unstack().fillna(0).astype(int)
    out.append("\n## Run status by configuration\n")
    out.append(fs.md_table(status_counts.reset_index()))
    ans = df[df.status == "solved"].groupby(["instance", "seed"]).result.nunique()
    out.append(f"\n\nConflicting SAT/UNSAT answers for the same (instance, seed): {(ans > 1).sum()}. "
               f"Wrong (failed verification): {(df.status == 'wrong').sum()}; unverified: {(df.status == 'unverified').sum()}.\n")

    # per (instance, seed) cost tables for every run configuration
    cost = df.pivot_table(index=["instance", "seed"], columns="config", values="par2", aggfunc="first")
    cpu = df.pivot_table(index=["instance", "seed"], columns="config", values="cpu", aggfunc="first")
    solved = df.assign(s=(df.status == "solved")).pivot_table(index=["instance", "seed"], columns="config",
                                                              values="s", aggfunc="first")
    # derived selectors
    if "static_selector" in fz:
        ss = fz["static_selector"]
        model = json.load(open(ss["model_file"]))
        insts = cost.index.get_level_values(0)
        X = static.loc[insts, model["features"]].values.astype(float)
        choose_b = eval_json(model, X) > 0.5
        fcpu = static.loc[insts, "cpu_time"].values.astype(float)
        base = np.where(choose_b, cpu[model["b"]].values, cpu[model["a"]].values)
        ok = np.where(choose_b, solved[model["b"]].values, solved[model["a"]].values).astype(bool)
        tot = base + fcpu
        cost[ss["name"]] = np.where(ok & (tot <= T), tot, 2 * T)
        solved[ss["name"]] = ok & (tot <= T)
        out.append(f"\nStatic selector `{ss['model_file']}` chose {model['b']} for "
                   f"{int(choose_b.sum())} of {len(choose_b)} (instance, seed) pairs.\n")
    if "random_oneshot" in fz:
        rd = fz["random_oneshot"]
        sel = np.array([coin(i, s, rd["salt"], rd["p"]) for i, s in cost.index])
        cost[rd["name"]] = np.where(sel, cost[rd["alt"]].values, cost[rd["base"]].values)
        solved[rd["name"]] = np.where(sel, solved[rd["alt"]].values, solved[rd["base"]].values)
        out.append(f"\nRandom one-shot (p = {rd['p']:.3f}, salt {rd['salt']}) switched on {int(sel.sum())} of "
                   f"{len(sel)} (instance, seed) pairs.\n")

    meta = df[["instance", "family_group", "split", "temporal_tag", "gbd_result"]].drop_duplicates("instance") \
        .set_index("instance")
    order = [fz["primary"]["name"]] + [c for c in fz["report_order"] if c != fz["primary"]["name"]]
    names = {fz["primary"]["config"]: fz["primary"]["name"]}
    names.update(fz.get("config_names", {}))
    cost = cost.rename(columns=names)
    solved = solved.rename(columns=names)
    results = {}
    for test_set, sel in (("test (family-disjoint)", meta.split == "test"),
                          ("t2026 (temporal)", meta.split == "t2026"),
                          ("t2026 seen families", (meta.split == "t2026") & (meta.temporal_tag == "seen")),
                          ("t2026 dev-test families", (meta.split == "t2026") & (meta.temporal_tag == "devtest")),
                          ("t2026 new families", (meta.split == "t2026") & (meta.temporal_tag == "new"))):
        insts = meta.index[sel]
        if len(insts) == 0:
            continue
        c = cost.loc[cost.index.get_level_values(0).isin(insts)]
        per = c.groupby(level=0).mean()  # mean over seeds
        sv = solved.loc[solved.index.get_level_values(0).isin(insts)]
        groups = meta.loc[per.index, "family_group"].values
        rows = []
        sbs = fz["sbs_name"]
        for name in order:
            if name not in per:
                continue
            p, lo, hi = fs.paired_relative_ci(per[sbs].values, per[name].values, groups, B=fz["bootstrap"])
            q, qlo, qhi = fs.paired_relative_ci(per["D (stock)"].values, per[name].values, groups, B=fz["bootstrap"])
            by_seed = sv.groupby(level=1)[name].sum()
            rows.append({"policy": name, "PAR2": per[name].mean(),
                         "solved/seed": " / ".join(str(int(v)) for v in by_seed.values),
                         "mean solved": by_seed.mean(),
                         "red vs SBS %": 100 * p, "CI lo": 100 * lo, "CI hi": 100 * hi,
                         "red vs D %": 100 * q, "D CI lo": 100 * qlo, "D CI hi": 100 * qhi})
        t = pd.DataFrame(rows)
        results[test_set] = rows
        out.append(f"\n## {test_set}: {len(insts)} instances, {len(set(groups))} family groups\n")
        out.append(fs.md_table(t, "{:.1f}"))
        # gains/losses of the candidate vs SBS
        cand = fz["primary"]["name"]
        gained = int(((sv[cand] == True) & (sv[sbs] == False)).sum())  # noqa: E712
        lost = int(((sv[cand] == False) & (sv[sbs] == True)).sum())  # noqa: E712
        worst = (per[cand] - per[sbs]).sort_values(ascending=False).head(5)
        out.append(f"\n\nCandidate vs SBS over all (instance, seed) pairs: newly solved {gained}, lost {lost}. "
                   f"Largest per-instance regressions (PAR2 s, seed mean): "
                   + ", ".join(f"{meta.loc[i, 'family_group']}/{i[:8]} +{v:.0f}" for i, v in worst.items() if v > 0)
                   + ".\n")
        # family forest for the main test set
        if test_set.startswith("test"):
            fam = pd.DataFrame({"g": groups, "c": per[cand].values, "s": per[sbs].values}).groupby("g").agg(
                n=("c", "size"), c=("c", "mean"), s=("s", "mean"))
            fam["delta"] = fam.c - fam.s
            fam = fam.sort_values("delta")
            fig, ax = plt.subplots(figsize=(6.4, 0.24 * len(fam) + 1.2), dpi=150)
            yy = np.arange(len(fam))
            ax.axvline(0, color=fs.INK2, linewidth=0.8)
            ax.scatter(fam.delta, yy, s=np.clip(fam.n * 4, 10, 140), color=fs.COLORS["D"], edgecolors="white",
                       linewidths=0.6, zorder=3)
            ax.set_yticks(yy)
            ax.set_yticklabels([f"{g} (n={r.n})" for g, r in fam.iterrows()], fontsize=7)
            ax.set_xlabel(f"mean PAR2 difference, candidate − {sbs} (s; < 0: candidate better)")
            ax.set_title("Held-out test families", fontsize=10)
            fs.style_axes(ax)
            fig.tight_layout()
            fig.savefig(os.path.join(a.out, "figures", "test_family_delta.png"))
            plt.close(fig)
            fig, ax = plt.subplots(figsize=(6.4, 4.2), dpi=150)
            pal = [fs.COLORS["D"], fs.COLORS["Fminus"], fs.COLORS["Iminus"], fs.COLORS["Fplus"]]
            for k, name in enumerate([cand, sbs, "D (stock)", "F− (forced negative)"]):
                if name not in c:
                    continue
                v = np.sort(np.concatenate([c[name].values]))
                v = v[v < 2 * T]
                ax.plot(np.arange(1, len(v) + 1) / len(fz["seeds"]), v, color=pal[k], linewidth=2, label=name)
            ax.set_xlabel("instances solved (averaged over seeds)")
            ax.set_ylabel("CPU s")
            ax.set_ylim(0, T * 1.02)
            fs.style_axes(ax)
            ax.legend(fontsize=8, frameon=False)
            ax.set_title("Cactus, held-out family-disjoint test", fontsize=10)
            fig.tight_layout()
            fig.savefig(os.path.join(a.out, "figures", "test_cactus.png"))
            plt.close(fig)
    with open(os.path.join(a.out, "tables.md"), "w") as f:
        f.write("\n".join(out) + "\n")
    with open(os.path.join(a.out, "numbers.json"), "w") as f:
        json.dump(results, f, indent=1, default=float)
    print("\n".join(out))


if __name__ == "__main__":
    main()
