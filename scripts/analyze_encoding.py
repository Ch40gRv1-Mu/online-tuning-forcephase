#!/usr/bin/env python3
"""H1 encoding sensitivity: F- vs D on original, globally flipped and randomly
flipped encodings of the same instances (dev only).

  scripts/analyze_encoding.py --census results/m2_census/runs.csv --enc results/m2_encoding/runs.csv --out reports/m2

Symmetry check: under 'flipall' every literal is negated, so F- on the
flipped CNF decides the original positive literal; the expected match is
F+ on the original (and D on flipall ~ I- on the original).  Search
statistics are compared to see whether CaDiCaL is exactly sign-symmetric.
"""

import argparse
import json
import os
import sys

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "analysis"))
import fpstats as fs  # noqa: E402


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--census", required=True)
    ap.add_argument("--enc", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    c = fs.load_runs(a.census)
    e = fs.load_runs(a.enc)
    T = float(c.timeout.iloc[0])
    insts = sorted(e.instance.unique())
    c = c[c.instance.isin(insts)]
    groups = fs.instance_meta(c).loc[insts, "family_group"].values

    def w(df, cfg, variant):
        d = df[(df.config == cfg) & (df.variant == variant)].set_index("instance")
        return d.reindex(insts)

    out = ["# Encoding sensitivity (generated by scripts/analyze_encoding.py)\n",
           f"Instances: {len(insts)} dev instances solved by D or F− on the original encoding.\n"]
    # symmetry check
    rows = []
    for enc_cfg, orig_cfg in (("Fminus", "Fplus"), ("D", "Iminus")):
        a1 = w(e, enc_cfg, "flipall")
        b1 = w(c, orig_cfg, "orig")
        both = (a1.status == "solved") & (b1.status == "solved")
        same = both & (a1.conflicts == b1.conflicts) & (a1.decisions == b1.decisions)
        rows.append({"flipall config": enc_cfg, "original config": orig_cfg, "both solved": int(both.sum()),
                     "identical conflicts+decisions": int(same.sum()),
                     "status agree": int((a1.status == b1.status).sum()),
                     "PAR2 flipall": a1.par2.mean(), "PAR2 original": b1.par2.mean()})
    out.append("\n## Symmetry check (flipall vs opposite-sign configuration on the original)\n")
    out.append(fs.md_table(pd.DataFrame(rows), "{:.1f}"))

    # main comparison: F- advantage over D per encoding
    rows = []
    adv = {}
    for variant, src in (("orig", c), ("flipall", e), ("flipr:1", e)):
        dD, dF = w(src, "D", variant), w(src, "Fminus", variant)
        p, lo, hi = fs.paired_relative_ci(dD.par2.values, dF.par2.values, groups)
        wl = fs.win_loss(dD.par2.values, dF.par2.values, T)
        rows.append({"encoding": variant, "PAR2 D": dD.par2.mean(), "PAR2 F−": dF.par2.mean(),
                     "F− red vs D %": 100 * p, "CI lo %": 100 * lo, "CI hi %": 100 * hi,
                     "solved D": int((dD.status == "solved").sum()), "solved F−": int((dF.status == "solved").sum()),
                     "F− faster": wl["b_better"], "D faster": wl["b_worse"]})
        adv[variant] = np.log2(dF.par2.values / dD.par2.values)
    out.append("\n\n## F− versus D under each encoding\n")
    out.append(fs.md_table(pd.DataFrame(rows), "{:.1f}"))
    # does the per-instance F- advantage survive random flips?
    r_orig_flipr = np.corrcoef(adv["orig"], adv["flipr:1"])[0, 1]
    r_orig_flipall = np.corrcoef(adv["orig"], adv["flipall"])[0, 1]
    sign_keep = np.mean(np.sign(adv["orig"]) == np.sign(adv["flipr:1"]))
    fam = pd.DataFrame({"family_group": groups, "orig": adv["orig"], "flipall": adv["flipall"],
                        "flipr": adv["flipr:1"]}).groupby("family_group").agg(
        n=("orig", "size"), orig=("orig", "mean"), flipall=("orig", lambda s: np.nan), flipr=("flipr", "mean"))
    fam["flipall"] = pd.DataFrame({"g": groups, "v": adv["flipall"]}).groupby("g").v.mean()
    fam = fam.sort_values("orig")
    out.append(f"\n\nPer-instance log2(PAR2 F− / PAR2 D): correlation original vs random flip r = {r_orig_flipr:.2f}; "
               f"original vs global flip r = {r_orig_flipall:.2f}; same sign (original vs random flip) "
               f"{100 * sign_keep:.0f}% of instances.\n")
    out.append("\n## Per family group: mean log2(PAR2 F− / PAR2 D) (negative = F− better)\n")
    out.append(fs.md_table(fam.reset_index(), "{:.2f}"))
    fig, ax = plt.subplots(figsize=(5.0, 4.6), dpi=150)
    ax.scatter(adv["orig"], adv["flipr:1"], s=12, color=fs.COLORS["Fminus"], edgecolors="white", linewidths=0.4)
    lim = max(np.abs(adv["orig"]).max(), np.abs(adv["flipr:1"]).max()) * 1.05
    ax.plot([-lim, lim], [-lim, lim], color=fs.INK2, linewidth=0.8)
    ax.axhline(0, color=fs.GRID, linewidth=0.8)
    ax.axvline(0, color=fs.GRID, linewidth=0.8)
    ax.set_xlabel("original: log2(PAR2 F− / PAR2 D)")
    ax.set_ylabel("random sign flip: log2(PAR2 F− / PAR2 D)")
    ax.set_title("F− advantage: original vs randomly flipped encoding", fontsize=10)
    fs.style_axes(ax)
    fig.tight_layout()
    os.makedirs(os.path.join(a.out, "figures"), exist_ok=True)
    fig.savefig(os.path.join(a.out, "figures", "encoding_flipr.png"))
    plt.close(fig)
    with open(os.path.join(a.out, "encoding.md"), "w") as f:
        f.write("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
