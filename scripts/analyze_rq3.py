#!/usr/bin/env python3
"""RQ3: does the preferred action change during search? (dev only)

  scripts/analyze_rq3.py --dataset results/m3/dataset.csv --census results/m2_census/runs.csv --out reports/m3

Uses the same-state replay pairs of results/m3/dataset.csv:
  * D prefix -> NEGATIVE at K in {1e3, 1e4, 1e5}: per instance, which of
    {stay NATIVE, switch at K} is cheaper, and whether the answer changes with K;
  * F- prefix -> NATIVE at 1e4 (reverse): is leaving F- better than staying?
  * oracles: static D/F-, best single switching time from a D prefix, and
    the union, to see how much value depends on *when* the action is taken.
All oracles use future information and are diagnostics only.
"""

import argparse
import collections
import os
import sys

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "analysis"))
import fpstats as fs  # noqa: E402

T = 300.0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dataset", required=True)
    ap.add_argument("--census", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    ds = pd.read_csv(a.dataset, dtype={"instance": str})
    census = fs.load_runs(a.census)
    census = census[census.split.isin(["train", "val"])]
    wide = fs.wide_cost(census, ["D", "Iminus", "Fminus", "Fplus"])
    meta = fs.instance_meta(census)
    insts = wide.index.values
    groups = meta.loc[insts, "family_group"].values
    out = ["# RQ3: time variation of the preferred action (generated by scripts/analyze_rq3.py)\n"]

    def branch(direction, K, track="C"):
        d = ds[(ds.direction == direction) & (ds.K == K) & (ds.track == track)].set_index("instance").reindex(insts)
        has = ((d.has_decision == 1) & (d.alt_run == 1)).values
        cb = d.cost_base.values.astype(float)
        ca = np.where(has, d.cost_alt.values.astype(float), cb)
        return has, cb, ca

    costs = {"D": wide.loc[insts, "D"].values, "F-": wide.loc[insts, "Fminus"].values,
             "I-": wide.loc[insts, "Iminus"].values}
    Ks = sorted(ds[ds.direction == "nat2neg"].K.unique())
    pref = {}
    for K in Ks:
        has, cb, ca = branch("nat2neg", K)
        costs[f"D→F- @{K}"] = ca
        lab = np.full(len(insts), "", dtype=object)
        lab[has & (ca < cb)] = "NEG"
        lab[has & (cb < ca)] = "NAT"
        lab[has & (ca == cb)] = "tie"
        lab[has & (ca >= 2 * T) & (cb >= 2 * T)] = "censored"
        lab[~has] = "solved-before"
        pref[K] = lab
    rows = []
    for K in Ks:
        c = collections.Counter(pref[K])
        rows.append({"K": K, **{k: c.get(k, 0) for k in ("NEG", "NAT", "tie", "censored", "solved-before")}})
    out.append("\n## Same-state preference at each K (D prefix; NEG = switching to F− at K is cheaper)\n")
    out.append(fs.md_table(pd.DataFrame(rows), "{:.0f}"))
    # pattern across K for instances informative at all K
    if len(Ks) >= 2:
        informative = np.all([np.isin(pref[K], ["NEG", "NAT"]) for K in Ks], axis=0)
        pats = collections.Counter("/".join(pref[K][i] for K in Ks) for i in np.flatnonzero(informative))
        changes = sum(v for k, v in pats.items() if len(set(k.split("/"))) > 1)
        out.append(f"\nInstances with an uncensored preference at every K ({', '.join(map(str, Ks))}): "
                   f"{int(informative.sum())}; preference changes with K for **{changes}** "
                   f"({100 * changes / max(1, informative.sum()):.0f}%).\n")
        out.append("\n| pattern (K ascending) | instances |\n|---|---|")
        for k, v in pats.most_common():
            out.append(f"| {k} | {v} |")
    # reverse direction
    if (ds.direction == "neg2nat").any():
        has, cb, ca = branch("neg2nat", 10000)
        costs["F-→D @10000"] = ca
        better = int((has & (ca < cb)).sum())
        worse = int((has & (cb < ca)).sum())
        out.append(f"\n\n## Reverse: F− prefix, switch to NATIVE at 1e4\n\nDecision points {int(has.sum())}: switching back "
                   f"cheaper on {better}, staying F− cheaper on {worse}; PAR2 stay F− {cb.mean():.1f} → always switch "
                   f"back {ca.mean():.1f} (D from start {costs['D'].mean():.1f}).\n")
    # oracles
    rows = []
    for name, keys in (("static D/F−", ["D", "F-"]),
                       ("D prefix, best single switch time", ["D"] + [f"D→F- @{K}" for K in Ks]),
                       ("static D/F− + best switch time", ["D", "F-"] + [f"D→F- @{K}" for K in Ks]),
                       ("all incl. reverse", [k for k in costs if k != "I-"])):
        keys = [k for k in keys if k in costs]
        v = np.min(np.vstack([costs[k] for k in keys]), axis=0)
        p, lo, hi = fs.paired_relative_ci(costs["D"], v, groups)
        q, qlo, qhi = fs.paired_relative_ci(costs["I-"], v, groups)
        rows.append({"oracle": name, "PAR2": v.mean(), "solved": int((v < 2 * T).sum()), "vs D %": 100 * p,
                     "vs I− %": 100 * q, "vs I− CI lo": 100 * qlo, "vs I− CI hi": 100 * qhi})
    for k in costs:
        rows.append({"oracle": f"(single policy) {k}", "PAR2": costs[k].mean(), "solved": int((costs[k] < 2 * T).sum()),
                     "vs D %": 100 * (1 - costs[k].mean() / costs["D"].mean()),
                     "vs I− %": 100 * (1 - costs[k].mean() / costs["I-"].mean()), "vs I− CI lo": np.nan,
                     "vs I− CI hi": np.nan})
    out.append("\n## Oracles over switching times (diagnostic, future information)\n")
    out.append(fs.md_table(pd.DataFrame(rows), "{:.1f}"))
    # figure: log2 ratio switch/stay per K for informative instances
    fig, ax = plt.subplots(figsize=(6.0, 3.6), dpi=150)
    for j, K in enumerate(Ks):
        has, cb, ca = branch("nat2neg", K)
        m = has & ~((ca >= 2 * T) & (cb >= 2 * T))
        r = np.log2(ca[m] / cb[m])
        ax.scatter(np.full(m.sum(), j) + np.random.default_rng(j).uniform(-0.25, 0.25, m.sum()), r, s=6,
                   color=fs.COLORS["Fminus"], alpha=0.6, edgecolors="none")
        ax.plot([j - 0.3, j + 0.3], [np.median(r)] * 2, color=fs.INK, linewidth=2)
    ax.axhline(0, color=fs.INK2, linewidth=0.8)
    ax.set_xticks(range(len(Ks)))
    ax.set_xticklabels([f"K = {K:,}" for K in Ks])
    ax.set_ylabel("log2(PAR2 switch→F− / PAR2 stay D)")
    ax.set_title("Same-state effect of switching to F− (uncensored pairs; bar = median)", fontsize=9)
    fs.style_axes(ax)
    fig.tight_layout()
    os.makedirs(os.path.join(a.out, "figures"), exist_ok=True)
    fig.savefig(os.path.join(a.out, "figures", "switch_effect_by_K.png"))
    plt.close(fig)
    with open(os.path.join(a.out, "rq3.md"), "w") as f:
        f.write("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
