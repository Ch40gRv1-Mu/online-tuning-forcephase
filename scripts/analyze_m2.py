#!/usr/bin/env python3
"""M2 static complementarity analysis (run with the analysis venv).

  scripts/analyze_m2.py --runs results/m2_census/runs.csv [--diag results/m2_diag/runs.csv] --out reports/m2

Writes tables.md (all numbers), numbers.json and figures/*.png, generated only
from the run CSVs.  Dev data only (train + val); no test split.
"""

import argparse
import json
import os
import sys

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "analysis"))
import fpstats as fs  # noqa: E402

MAIN = ["D", "Iminus", "Fminus", "Fplus"]
DIAG = ["D_noR", "Iminus_noR", "S_saved", "P_neg"]


def scatter(ax, x, y, ans, T, xl, yl):
    lim_lo, lim_hi = 0.05, 2 * T * 1.15
    xs = np.clip(x, lim_lo, None)
    ys = np.clip(y, lim_lo, None)
    groups = [("SAT", fs.COLORS["D"]), ("UNSAT", fs.COLORS["Fminus"]), ("unknown", fs.COLORS["Iminus"])]
    for name, col in groups:
        m = (ans == name).values
        ax.scatter(xs[m], ys[m], s=14, color=col, alpha=0.85, linewidths=0.4, edgecolors="white",
                   label=f"{name} (n={m.sum()})")
    ax.plot([lim_lo, lim_hi], [lim_lo, lim_hi], color=fs.INK2, linewidth=0.8)
    for k, ls in ((2, ":"), (0.5, ":")):
        ax.plot([lim_lo, lim_hi], [lim_lo * k, lim_hi * k], color=fs.GRID, linewidth=0.8, linestyle=ls)
    ax.axvline(T, color=fs.INK2, linewidth=0.6, linestyle="--")
    ax.axhline(T, color=fs.INK2, linewidth=0.6, linestyle="--")
    ax.set_xscale("log")
    ax.set_yscale("log")
    ax.set_xlim(lim_lo, lim_hi)
    ax.set_ylim(lim_lo, lim_hi)
    ax.set_xlabel(xl)
    ax.set_ylabel(yl)
    ax.text(2 * T, lim_lo * 1.3, "timeout\n(=2T)", fontsize=7, color=fs.INK2, ha="center")
    fs.style_axes(ax)
    ax.legend(fontsize=7, frameon=False, loc="upper left")


def cactus(ax, df, configs, T):
    for c in configs:
        d = df[(df.config == c) & (df.status == "solved")].cpu.sort_values().values
        ax.plot(np.arange(1, len(d) + 1), d, color=fs.COLORS[c], linewidth=2, label=f"{fs.LABELS[c]} ({len(d)})")
    ax.set_xlabel("instances solved")
    ax.set_ylabel("CPU seconds (incl. LRAT proof output)")
    ax.set_ylim(0, T * 1.02)
    fs.style_axes(ax)
    ax.legend(fontsize=8, frameon=False, loc="upper left")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", required=True)
    ap.add_argument("--diag")
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    os.makedirs(os.path.join(a.out, "figures"), exist_ok=True)
    df = fs.load_runs(a.runs)
    if a.diag and os.path.exists(a.diag):
        df = pd.concat([df, fs.load_runs(a.diag)], ignore_index=True)
    df = df[df.split.isin(["train", "val"])]
    T = float(df.timeout.iloc[0])
    meta = fs.instance_meta(df)
    ans, conflicts = fs.observed_answer(df)
    ans_full = pd.Series("unknown", index=meta.index)
    ans_full.loc[ans.index] = ans
    configs = [c for c in MAIN + DIAG if c in set(df.config)]
    out = []
    numbers = {"T": T, "answer_conflicts": conflicts}

    out.append(f"# M2 tables (generated by scripts/analyze_m2.py; T = {T:.0f} s CPU)\n")
    out.append(f"Instances: train {int((meta.split == 'train').sum())}, val {int((meta.split == 'val').sum())}. "
               f"Observed answers (verified): SAT {(ans_full == 'SAT').sum()}, UNSAT {(ans_full == 'UNSAT').sum()}, "
               f"unsolved by every configuration {(ans_full == 'unknown').sum()}. "
               f"Conflicting SAT/UNSAT answers across configurations: {len(conflicts)}.\n")
    status_all = df.status.value_counts().to_dict()
    out.append(f"Run status counts (all configurations): {status_all}\n")
    numbers["status_counts"] = status_all

    for split_name, splits in (("train+val", ["train", "val"]), ("train", ["train"]), ("val", ["val"])):
        d = df[df.split.isin(splits)]
        t = fs.summary_table(d, configs, T)
        out.append(f"\n## Summary, {split_name}\n")
        out.append(fs.md_table(t))
        numbers[f"summary_{split_name}"] = t.to_dict(orient="records")

    # SBS on validation (pre-registered: among D, I-, F-, F+)
    val = df[df.split == "val"]
    wv = fs.wide_cost(val, MAIN)
    sbs = wv.mean().idxmin()
    wv2 = fs.wide_cost(val, ["D", "Fminus"])
    sbs2 = wv2.mean().idxmin()
    numbers["validation_SBS"] = sbs
    numbers["validation_SBS_two_action"] = sbs2
    out.append(f"\n## Validation-SBS\n\nAmong D/I−/F−/F+ on val (mean PAR2): **{sbs}** "
               f"({', '.join(f'{c} {v:.1f}' for c, v in wv.mean().items())}). Two-action SBS among D/F−: **{sbs2}**.\n")

    # oracle gaps
    out.append("\n## Static oracle (VBS) gap — diagnostic only, uses future information\n")
    rows = []
    for split_name, splits in (("train+val", ["train", "val"]), ("train", ["train"]), ("val", ["val"])):
        d = df[df.split.isin(splits)]
        w = fs.wide_cost(d, MAIN)
        g = meta.loc[w.index, "family_group"].values
        for cand, sb in ((["D", "Fminus"], "D"), (MAIN, sbs)):
            vbs = w[cand].min(axis=1)
            p, lo, hi = fs.paired_relative_ci(w[sb], vbs, g)
            rows.append({"split": split_name, "portfolio": "+".join(cand), "SBS": sb, "PAR2_SBS": w[sb].mean(),
                         "PAR2_VBS": vbs.mean(), "gap_%": 100 * p, "CI_lo_%": 100 * lo, "CI_hi_%": 100 * hi,
                         "VBS_solved": int((vbs < 2 * T).sum()), "SBS_solved": int((w[sb] < 2 * T).sum())})
    gap = pd.DataFrame(rows)
    out.append(fs.md_table(gap))
    numbers["oracle_gap"] = rows

    # pairwise vs D
    out.append("\n\n## Pairwise comparison with D (train+val)\n")
    w = fs.wide_cost(df, configs)
    g = meta.loc[w.index, "family_group"].values
    rows = []
    for c in configs:
        if c == "D":
            continue
        p, lo, hi = fs.paired_relative_ci(w["D"], w[c], g)
        wl = fs.win_loss(w["D"], w[c], T)
        wl2 = fs.win_loss(w["D"], w[c], T, factor=2.0)
        only_c = int(((w[c] < 2 * T) & (w["D"] >= 2 * T)).sum())
        only_d = int(((w["D"] < 2 * T) & (w[c] >= 2 * T)).sum())
        rows.append({"config": c, "PAR2_red_vs_D_%": 100 * p, "CI_lo_%": 100 * lo, "CI_hi_%": 100 * hi,
                     "faster": wl["b_better"], "slower": wl["b_worse"], "faster_2x": wl2["b_better"],
                     "slower_2x": wl2["b_worse"], "both_TO": wl["both_timeout"],
                     "solved_only_by_it": only_c, "solved_only_by_D": only_d})
    pw = pd.DataFrame(rows)
    out.append(fs.md_table(pw))
    out.append("\nPAR2_red_vs_D_% > 0 means the configuration has lower mean PAR2 than D; CI: 95% family-group "
               "cluster bootstrap (10,000 resamples, seed 12345).\n")
    numbers["pairwise_vs_D"] = rows

    # SAT/UNSAT strata (post hoc, observed answers)
    out.append("\n## By observed answer (post hoc stratification)\n")
    rows = []
    for stratum in ("SAT", "UNSAT", "unknown"):
        idx = ans_full.index[ans_full == stratum]
        if len(idx) == 0:
            continue
        r = {"stratum": stratum, "instances": len(idx)}
        for c in configs:
            r[f"{c}_solved"] = int((w.loc[idx, c] < 2 * T).sum())
            r[f"{c}_PAR2"] = w.loc[idx, c].mean()
        rows.append(r)
    out.append(fs.md_table(pd.DataFrame(rows)))
    numbers["strata"] = rows

    # family table D vs F-
    out.append("\n\n## Families (train+val): D vs F−\n")
    fam = []
    for grp, idx in meta.loc[w.index].groupby("family_group").groups.items():
        sub = w.loc[idx]
        both_to = ((sub["D"] >= 2 * T) & (sub["Fminus"] >= 2 * T)).sum()
        fam.append({"family_group": grp, "split": meta.loc[idx[0], "split"], "n": len(idx),
                    "D_solved": int((sub["D"] < 2 * T).sum()), "F-_solved": int((sub["Fminus"] < 2 * T).sum()),
                    "D_PAR2": sub["D"].mean(), "F-_PAR2": sub["Fminus"].mean(),
                    "F-_faster": int((sub["Fminus"] < sub["D"]).sum() - 0),
                    "D_faster": int((sub["D"] < sub["Fminus"]).sum()), "both_TO": int(both_to),
                    "log2_ratio": float(np.log2(sub["Fminus"].mean() / sub["D"].mean()))})
    famdf = pd.DataFrame(fam).sort_values("log2_ratio")
    out.append(fs.md_table(famdf, floatfmt="{:.2f}"))
    numbers["families"] = fam

    # figures
    fig, ax = plt.subplots(figsize=(5.2, 5.0), dpi=150)
    scatter(ax, w["D"].values, w["Fminus"].values, ans_full.loc[w.index], T,
            "D (stock) CPU s, PAR2", "F− (forced negative) CPU s, PAR2")
    ax.set_title("D vs F− per instance, train+val", fontsize=10)
    fig.tight_layout()
    fig.savefig(os.path.join(a.out, "figures", "scatter_D_Fminus.png"))
    plt.close(fig)
    for other in ("Iminus", "Fplus", "Iminus_noR", "P_neg"):
        if other in w:
            fig, ax = plt.subplots(figsize=(5.2, 5.0), dpi=150)
            base = "Fminus" if other in ("Iminus_noR", "Fplus") else "D"
            scatter(ax, w[base].values, w[other].values, ans_full.loc[w.index], T,
                    f"{fs.LABELS[base]} CPU s", f"{fs.LABELS[other]} CPU s")
            ax.set_title(f"{fs.LABELS[base]} vs {fs.LABELS[other]}, train+val", fontsize=10)
            fig.tight_layout()
            fig.savefig(os.path.join(a.out, "figures", f"scatter_{base}_{other}.png"))
            plt.close(fig)
    fig, ax = plt.subplots(figsize=(6.4, 4.2), dpi=150)
    cactus(ax, df, MAIN, T)
    ax.set_title("Cactus, train+val (verified solved only)", fontsize=10)
    fig.tight_layout()
    fig.savefig(os.path.join(a.out, "figures", "cactus_main.png"))
    plt.close(fig)
    if any(c in df.config.values for c in DIAG):
        fig, ax = plt.subplots(figsize=(6.4, 4.2), dpi=150)
        cactus(ax, df, ["D", "Fminus"] + [c for c in DIAG if c in df.config.values][:3], T)
        ax.set_title("Cactus with mechanism diagnostics, train+val", fontsize=10)
        fig.tight_layout()
        fig.savefig(os.path.join(a.out, "figures", "cactus_diag.png"))
        plt.close(fig)
    # family dot plot
    f2 = famdf[(famdf.n >= 3) & ~((famdf["D_solved"] == 0) & (famdf["F-_solved"] == 0))]
    fig, ax = plt.subplots(figsize=(6.4, 0.22 * len(f2) + 1.2), dpi=150)
    yy = np.arange(len(f2))
    ax.axvline(0, color=fs.INK2, linewidth=0.8)
    ax.scatter(f2.log2_ratio, yy, s=np.clip(f2.n * 3, 10, 120), color=fs.COLORS["Fminus"], zorder=3,
               edgecolors="white", linewidths=0.6)
    ax.set_yticks(yy)
    ax.set_yticklabels([f"{r.family_group} ({r.split}, n={r.n})" for r in f2.itertuples()], fontsize=7)
    ax.set_xlabel("log2(PAR2 F− / PAR2 D)   (< 0: F− better)")
    fs.style_axes(ax)
    ax.set_title("F− vs D per family group\n(n ≥ 3, ≥ 1 solved; train+val)", fontsize=10)
    fig.tight_layout()
    fig.savefig(os.path.join(a.out, "figures", "family_log2ratio.png"))
    plt.close(fig)

    with open(os.path.join(a.out, "tables.md"), "w") as f:
        f.write("\n".join(out) + "\n")
    with open(os.path.join(a.out, "numbers.json"), "w") as f:
        json.dump(numbers, f, indent=1, default=float)
    print("\n".join(out[:12]))


if __name__ == "__main__":
    main()
