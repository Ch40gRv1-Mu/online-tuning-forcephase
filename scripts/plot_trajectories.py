#!/usr/bin/env python3
"""Trajectory explanations for representative dev instances (M2/M4 deliverable).

  scripts/plot_trajectories.py --out reports/trajectories

Instances are picked by fixed rules (not by eye), so that wins and
counterexamples are both shown:
  A  largest F− speed-up over D (PAR2 ratio) among dev instances solved by both
  B  largest F− loss vs D among instances D solves (F− PAR2 / D PAR2)
  C  largest gain of F−→D @1e4 over D among instances where the switch happened
  D  largest loss of F−→D @1e4 vs I− (validation-SBS)
For each instance the telemetry windows/checkpoints of D, I−, F− and F−→D @1e4
are plotted against conflicts: CPU time, mean learned glue (window), share of
negative free decisions (window) and best-assignment fraction.
"""

import argparse
import gzip
import json
import os
import sys

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "analysis"))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fpstats as fs  # noqa: E402
import fprun  # noqa: E402

T = 300.0
CFG = {"D": ("D (stock)", fs.COLORS["D"]), "Iminus": ("I−", fs.COLORS["Iminus"]),
       "Fminus": ("F−", fs.COLORS["Fminus"]), "sw10k_Crev": ("F−→D @1e4", fs.COLORS["Fplus"])}


def records(run_id):
    p = os.path.join(fprun.raw_dir(run_id), "telemetry.jsonl.gz")
    out = []
    with gzip.open(p, "rt") as f:
        for line in f:
            try:
                x = json.loads(line)
            except json.JSONDecodeError:
                continue
            if x.get("type") in ("window", "checkpoint", "switch"):
                out.append(x)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    runs = pd.concat([fs.load_runs("results/m2_census/runs.csv"), fs.load_runs("results/m3_replay/runs.csv")])
    runs = runs[runs.config.isin(CFG) & runs.split.isin(["train", "val"])]
    w = runs.pivot_table(index="instance", columns="config", values="par2", aggfunc="first")
    sw = runs[runs.config == "sw10k_Crev"].set_index("instance")
    w["sw10k_Crev"] = sw.par2.reindex(w.index).fillna(w["Fminus"])
    meta = fs.instance_meta(runs)
    both = (w.D < 2 * T) & (w.Fminus < 2 * T)
    picks = {}
    picks["A"] = (w[both].Fminus / w[both].D.clip(lower=0.1)).idxmin()
    dsolved = w.D < 2 * T
    picks["B"] = (w[dsolved].Fminus / w[dsolved].D.clip(lower=0.1)).idxmax()
    switched = w.index.isin(sw.index[sw.switches.fillna(0) > 0])
    picks["C"] = (w[switched].sw10k_Crev - w[switched].D).idxmin()
    picks["D"] = (w[switched].sw10k_Crev - w[switched].Iminus).idxmax()
    rule = {"A": "largest F− speed-up over D (both solved)", "B": "largest F− slow-down vs D (D solved)",
            "C": "largest gain of F−→D @1e4 over D", "D": "largest loss of F−→D @1e4 vs I−"}
    lines = ["# Trajectory explanations (generated by scripts/plot_trajectories.py)\n",
             "Selection rules are fixed in the script; values are PAR2 seconds (600 = timeout).\n"]
    for key, inst in picks.items():
        row = w.loc[inst]
        lines.append(f"\n## {key}: {rule[key]} — `{inst[:12]}` ({meta.loc[inst, 'family_group']}, "
                     f"{meta.loc[inst, 'split']}, GBD result {meta.loc[inst, 'gbd_result']})\n")
        lines.append("| config | PAR2 |\n|---|---|")
        for c in CFG:
            lines.append(f"| {CFG[c][0]} | {row[c]:.1f} |")
        fig, axes = plt.subplots(1, 4, figsize=(13, 3.0), dpi=130)
        for c, (label, col) in CFG.items():
            r = runs[(runs.config == c) & (runs.instance == inst)]
            if r.empty:
                continue
            recs = [x for x in records(r.run_id.iloc[0]) if x["type"] in ("window", "checkpoint")]
            recs.sort(key=lambda x: x["conflicts"])
            if not recs:
                continue
            x = np.array([v["conflicts"] for v in recs], float)
            series = [np.array([v["time"] for v in recs]),
                      np.array([v["f"].get("w_glue_mean") or np.nan for v in recs], float),
                      np.array([v["f"].get("w_neg_dec_frac") or np.nan for v in recs], float),
                      np.array([v["f"].get("x_best_frac") or np.nan for v in recs], float)]
            for ax, y in zip(axes, series):
                ax.plot(x, y, color=col, linewidth=1.6, label=label)
            for s in [v for v in records(r.run_id.iloc[0]) if v["type"] == "switch"]:
                axes[0].axvline(s["conflicts"], color=col, linewidth=0.8, linestyle=":")
        for ax, t in zip(axes, ["CPU s", "mean glue (window)", "negative free decisions (window)",
                                "best assignment / active vars"]):
            ax.set_xscale("log")
            ax.set_xlabel("conflicts")
            ax.set_title(t, fontsize=9)
            fs.style_axes(ax)
        axes[0].legend(fontsize=7, frameon=False)
        fig.suptitle(f"{key}: {rule[key]} — {meta.loc[inst, 'family_group']} ({inst[:8]})", fontsize=10)
        fig.tight_layout()
        fn = f"trajectory_{key}.png"
        fig.savefig(os.path.join(a.out, fn))
        plt.close(fig)
        lines.append(f"\n![{key}]({fn})\n")
    with open(os.path.join(a.out, "trajectories.md"), "w") as f:
        f.write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
